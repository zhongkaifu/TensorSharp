class ScenarioFailure(Exception):
    pass


class ScenarioUntested(Exception):
    pass


def _kind(case):
    return case.get("adapter") or case.get("kind") or case["id"]


def _fixture(case, context):
    fixture = dict(case.get("fixture") or {})
    kind = _kind(case)
    if kind in {"cli_image", "cli_audio", "cli_video"} and context.get("media_dir"):
        defaults = {"cli_image": ("image.png", "Read the main product name shown in the attached image.", r"tensorsharp"),
                    "cli_audio": ("sample.wav", "Transcribe the first sentence of the attached audio.", r"\bfox\b"),
                    "cli_video": ("sample.mp4", "Read the main product name shown in the attached video.", r"tensorsharp")}
        filename, prompt, expected = defaults[kind]
        for key, value in (("media_path", str(Path(context["media_dir"]) / filename)), ("prompt", prompt), ("expected_regex", expected)):
            fixture.setdefault(key, value)
    return fixture


def availability(case, context):
    """Return (available, reason), without executing anything or touching the network."""
    kind = _kind(case)
    if kind not in ADAPTER_IDS:
        return False, "scenario has a documented recipe but no executable adapter"
    command_key = "logit_command" if kind.startswith("forced_logits") else "server_command" if kind.startswith("server_") else "cli_command"
    command = context.get(command_key)
    if not command or isinstance(command, str):
        return False, "provide a built local binary argv list in " + command_key
    if kind.startswith("forced_logits") and context.get("backend") not in _LOGIT_BACKENDS:
        return False, "ForcedLogitProbe does not implement this backend; no fallback will run"
    if not context.get("preparing_model") and (not context.get("model_path") or not Path(context["model_path"]).is_file()):
        return False, "verified local model is not available"
    if kind in {"cli_image", "cli_audio", "cli_video"}:
        fixture = _fixture(case, context)
        if not fixture.get("media_path") or not Path(fixture["media_path"]).is_file():
            return False, "media fixture is absent; supply a generated public/synthetic fixture"
        if not fixture.get("prompt") or not fixture.get("expected_regex"):
            return False, "media fixture needs a prompt and scenario-specific expected_regex"
        if kind in {"cli_image", "cli_video"} and not context.get("model_options", {}).get("mmproj"):
            return False, "a verified vision projector is required for this fixture"
    return True, "adapter prerequisites present; runtime support still requires execution"


def _require(result, name, condition, expected=None, actual=None):
    result["assertions"].append({"name": name, "passed": bool(condition), "expected": expected, "actual": actual})
    if not condition:
        raise ScenarioFailure(name)


def _json_loads(value):
    def reject(value):
        raise ValueError("nonfinite JSON number: " + value)
    return json.loads(value, parse_constant=reject)


def _finite_json(value):
    if isinstance(value, float) and not math.isfinite(value):
        return {"nonfinite": str(value)}
    if isinstance(value, dict):
        return {k: _finite_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_finite_json(v) for v in value]
    return value


def _token_hash(tokens):
    digest = hashlib.sha256()
    for token in tokens:
        digest.update(struct.pack("<i", token))
    return digest.hexdigest()


def _history_hashes(case):
    prompt, forced = case["prompt_tokens"], case["generated_tokens"]
    return {"prompt_tokens_sha256": _token_hash(prompt), "forced_tokens_sha256": _token_hash(forced),
            "input_history_sha256": _token_hash(prompt + forced[:-1])}


def _ensure_logit_disk(context, result, *, sequence=False):
    root = Path(context["artifact_dir"]).resolve()
    while not root.exists():
        root = root.parent
    free = shutil.disk_usage(root).free
    reserve = 1024 ** 3 if sequence else 256 * 1024 ** 2
    headroom = int(context.get("disk_headroom_gib", 5) * 1024 ** 3)
    required = reserve + headroom
    result["evidence"].setdefault("artifact_disk_checks", []).append({"path": str(root), "available_bytes": free,
        "headroom_bytes": headroom, "estimated_next_artifacts_bytes": reserve, "required_bytes": required})
    if free < required:
        raise ScenarioUntested("insufficient free disk for logit diagnostics plus reserved headroom")


def backend_evidence(text, expected):
    """The ModelBase banner is emitted after successful backend allocation, not argv parsing."""
    canonical = lambda s: re.sub(r"[_\-]", "", s).lower()
    values = re.findall(r"(?m)^\s*Backend:\s*([A-Za-z_]+)\s*$", text)
    fallback = re.search(r"(?i)(?:backend[^\n]{0,60}(?:falling back|fallback)|(?:falling back|fallback)[^\n]{0,60}(?:backend|to cpu))", text)
    matching = bool(values) and all(canonical(v) == canonical(expected) for v in values)
    return {"requested": expected, "observed": values, "fallback": fallback.group(0) if fallback else None,
            "verified": matching and fallback is None}


def extract_assistant(stdout):
    marker = "=== Generated Output ==="
    if marker not in stdout:
        return ""
    text = stdout.split(marker, 1)[1].lstrip("\r\n")
    lines = []
    for line in text.splitlines():
        if re.match(r"^(?:\d\d:\d\d:\d\d\s+)?(?:info|warn|warning|error|critical|trace|debug|fail|crit):\s", line, re.I):
            break
        lines.append(line)
    answer = "\n".join(lines).strip()
    # Thinking is explicitly formatted by FormatParsedResult; an answer mentioned
    # only in that section cannot satisfy a visible-final-answer assertion.
    return re.sub(r"--- Thinking ---.*?--- End Thinking ---", "", answer, flags=re.S).strip()


def _process(context, result, command, stage):
    item = run_process(command, cwd=context["repo"], artifact_dir=context["artifact_dir"], stage=stage,
                       timeout_seconds=context.get("timeout_seconds", 600), env=context.get("env"))
    result["processes"].append({k: v for k, v in item.items() if k not in {"stdout", "stderr"}})
    return item


def _check_process(result, item, backend):
    _require(result, item["stage"] + ": no timeout", not item["timed_out"], False, item["timed_out"])
    _require(result, item["stage"] + ": process exit", item["exit_code"] == 0, 0, item["exit_code"])
    _require(result, item["stage"] + ": full output captured", not item["output_truncated"], False, item["output_truncated"])
    evidence = backend_evidence(item["stdout"] + "\n" + item["stderr"], backend)
    result["evidence"].setdefault("backend", []).append(evidence)
    _require(result, item["stage"] + ": actual backend", evidence["verified"], backend, evidence)


def _validate_config(path):
    value = _json_loads(Path(path).read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ScenarioFailure("effective config must be an object")
    for key, item in value.items():
        if key not in _CONFIG_KEYS or isinstance(item, (dict, list)):
            raise ScenarioFailure("effective config contains an unapproved option or download object: " + key)
    return value


def _base_args(context, kind):
    args = []
    if context.get("effective_config_path"):
        _validate_config(context["effective_config_path"])
        args += ["--config", str(context["effective_config_path"])]
    args += ["--model", str(context["model_path"]), "--backend", context["backend"], "--no-skills"]
    options = context.get("model_options", {})
    media = kind in {"cli_image", "cli_audio", "cli_video"}
    args += ["--mmproj", str(options.get("mmproj", "none")) if media else "none"]
    args += ["--max-tokens", "128", "--temperature", "0", "--top-k", "1", "--top-p", "1",
             "--min-p", "0", "--repeat-penalty", "1", "--seed", "42"]
    return args


def _cli(case, context, result):
    kind, fixture = _kind(case), _fixture(case, context)
    root = Path(context["artifact_dir"])
    args = list(context["cli_command"]) + _base_args(context, kind) + ["--log-level", "info", "--log-file", "off"]
    expected, prompt = fixture.get("expected_regex", _ANSWER), fixture.get("prompt", _PROMPT)
    repeat = kind in {"cli_text", "cli_prefill", "cli_decode"}
    if kind in {"cli_prefill", "cli_decode"}:
        prefill, decode = (128, 0) if kind == "cli_prefill" else (32, 16)
        args += ["--benchmark", "--bench-prefill", str(prefill), "--bench-decode", str(decode),
                 "--bench-runs", "1", "--bench-fixed-tokens"]
        result["inputs"] = {"prefill_tokens": prefill, "decode_tokens": decode, "fixed_tokens": True}
    elif kind == "cli_multi_turn":
        turns = [{"content": "My name is Alex and my favourite colour is teal. Remember that.", "max_tokens": 128},
                 {"content": "What is my name? Reply only with my name.", "max_tokens": 128},
                 {"content": "What is my favourite colour? Reply only with that colour.", "max_tokens": 128, "force_reset": True}]
        turns_file = root / "turns.jsonl"
        turns_file.write_text("".join(json.dumps(t) + "\n" for t in turns), encoding="utf-8")
        args += ["--multi-turn-jsonl", str(turns_file)]
        result["inputs"] = {"turns": turns, "limitations": "Reset uses full supplied conversation; raw KV equivalence is covered separately by logits probes."}
    else:
        if kind == "cli_thinking":
            prompt = (Path(context["repo"]) / "TensorSharp.TestMatrix/Inputs/prompts/thinking_question.txt").read_text(encoding="utf-8")
            expected = r"10:38"
            args += ["--think", "--max-tokens", "512"]
        elif kind == "cli_tools":
            prompt = "Call get_regression_value with key fixture. Do not answer without calling the function."
            tools = root / "tools.json"
            tools.write_text(json.dumps([_TOOL]), encoding="utf-8")
            args += ["--tools", str(tools)]
        elif kind in {"cli_image", "cli_audio", "cli_video"}:
            args += ["--" + kind.removeprefix("cli_"), str(fixture["media_path"])]
            digest = hashlib.sha256()
            with Path(fixture["media_path"]).open("rb") as media_file:
                for chunk in iter(lambda: media_file.read(1024 * 1024), b""):
                    digest.update(chunk)
            result["evidence"]["media_sha256"] = digest.hexdigest()
        prompt_file = root / "prompt.txt"
        prompt_file.write_text(prompt, encoding="utf-8")
        args += ["--input", str(prompt_file), "--warmup-runs", "0"]
        result["inputs"] = {"prompt": prompt, "expected_regex": expected, "seed": 42, "temperature": 0}
    outputs = []
    for index in range(2 if repeat else 1):
        item = _process(context, result, args, "cli-" + str(index + 1))
        _check_process(result, item, context["backend"])
        combined = item["stdout"] + "\n" + item["stderr"]
        if kind in {"cli_prefill", "cli_decode"}:
            _require(result, "benchmark executed requested shape", f"prefillTokens={prefill} decodeTokens={decode} runs=1" in combined)
            metrics = re.search(r"benchmark summary:\s*bestPrefillMs=(\S+) bestPrefillTps=(\S+) bestDecodeMs=(\S+) bestDecodeTps=(\S+)", combined)
            _require(result, "benchmark has measured metrics", metrics is not None)
            values = [float(x) for x in metrics.groups()]
            _require(result, "prefill throughput finite and positive", math.isfinite(values[1]) and values[1] > 0, ">0", values[1])
            if decode:
                _require(result, "decode throughput finite and positive", math.isfinite(values[3]) and values[3] > 0, ">0", values[3])
            tokens = re.search(r"benchmark sampled tokens \(untimed correctness\): prefillTopToken=(\d+) decode=([0-9,]*)", combined)
            _require(result, "benchmark correctness tokens present", tokens is not None)
            ids = [int(x) for x in tokens[2].split(",") if x]
            _require(result, "benchmark decode token count", len(ids) == decode, decode, len(ids))
            outputs.append({"prefill_top": int(tokens[1]), "decode": ids})
        elif kind == "cli_multi_turn":
            previews = re.findall(r"multi-turn content chars=\d+.*?preview=(.*)", combined)
            _require(result, "all three turns completed", len(previews) == 3, 3, len(previews))
            _require(result, "second turn remembers name", bool(re.search(r"\balex\b", previews[1], re.I)), "Alex", previews[1])
            _require(result, "third turn survives explicit reset", bool(re.search(r"\bteal\b", previews[2], re.I)), "teal", previews[2])
            _require(result, "reset executed", "forcing KV cache reset" in combined)
            outputs.append(previews)
        else:
            answer = extract_assistant(item["stdout"])
            _require(result, "assistant output is present", bool(answer), "nonempty generated output", answer)
            _require(result, "no inference error text", not re.search(r"(?:^|\n)\s*(?:Error:|Exception:|<unused)", answer, re.I), "answer", answer)
            if kind == "cli_tools":
                function = re.search(r"Function:\s*(\w+)", answer)
                arguments = re.search(r"Arguments:\s*(\{.*?\})", answer, re.S)
                _require(result, "tool function identity", bool(function) and function[1] == _TOOL["name"], _TOOL["name"], function[1] if function else None)
                _require(result, "tool arguments JSON", arguments is not None)
                actual = _json_loads(arguments[1])
                _require(result, "tool fixture argument", actual == {"key": "fixture"}, {"key": "fixture"}, actual)
            else:
                _require(result, "semantic fixture answer", re.search(expected, answer, re.I) is not None, expected, answer)
            outputs.append(answer)
            metric = re.search(r"decode complete:\s*tokens=(\d+)", combined)
            _require(result, "decode produced tokens", bool(metric) and int(metric[1]) > 0, ">0", metric[1] if metric else None)
            finish = re.search(r"cli\.inference finishReason=(\w+)", combined)
            _require(result, "completion finished without budget exhaustion", bool(finish) and finish[1] in {"eos", "stop", "stop_sequence"}, "eos/stop/stop_sequence", finish[1] if finish else None)
            if kind in {"cli_image", "cli_audio", "cli_video"}:
                pattern = (r"Audio encoder:\s*\[[1-9]\d*,\s*[1-9]\d*\]\s*done" if kind == "cli_audio" else
                           r"(?:Injected\s+[1-9]\d*\s+vision\s+(?:tokens|embeddings)|installed\s+[1-9]\d*\s+image soft tokens)")
                observed = re.search(fixture.get("media_evidence_regex", pattern), combined, re.I)
                if not observed:
                    raise ScenarioUntested("semantic media answer passed, but this architecture emitted no recognized positive encoder/injection evidence; extend its evidence adapter before claiming coverage")
                result["evidence"]["media_execution"] = observed.group(0)
    if repeat:
        _require(result, "deterministic fresh-process replay", outputs[0] == outputs[1], outputs[0], outputs[1])
    result["evidence"]["outputs"] = outputs


def validate_logit_metrics(metrics, run_id, *, comparison):
    """Reject incomplete/stale/nonfinite runs even if an executable returns zero."""
    if metrics.get("run_id") != run_id or metrics.get("complete") is not True or metrics.get("all_finite") is not True:
        raise ScenarioFailure("logits run is stale, incomplete, or nonfinite")
    cases = metrics.get("cases", [])
    if not cases or metrics.get("cases_done") != len(cases) or metrics.get("cases_total") != len(cases):
        raise ScenarioFailure("logits case count is incomplete")
    first = None
    for case in cases:
        rows = case.get("metrics", [])
        if case.get("steps", 0) < 16 or len(rows) != case["steps"]:
            raise ScenarioFailure("logits case has insufficient rows")
        for step, row in enumerate(rows):
            bad = row.get("finite") is not True or row.get("step") != step
            if comparison:
                numbers = [row.get("relative_l2"), row.get("cosine"), row.get("kl"), row.get("max_abs")]
                bad |= not all(isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x) for x in numbers)
                if not bad:
                    bad = (numbers[0] > 0.001 or numbers[1] < 0.999999 or row.get("top1_equal") is not True)
            if bad and first is None:
                first = {"case": case.get("name"), "step": step, "row": row}
    if comparison and metrics.get("qualified") is not True and first is None:
        raise ScenarioFailure("logit probe did not qualify")
    return first


def _logits(case, context, result):
    root = Path(context["artifact_dir"])
    fixtures = [{"name": "arithmetic", "prompt": "7 multiplied by 8 equals "},
                {"name": "synthetic_prefill128", "prompt_tokens": [1], "target_tokens": 128}]
    fixture_file = root / "logit-cases.json"
    fixture_file.write_text(json.dumps(fixtures), encoding="utf-8")
    result["inputs"] = {"cases": fixtures, "steps": 16, "comparison": "same-backend fresh-process fixed-history repeatability",
                        "limitations": "Not an independent quality oracle or cross-backend numerical certification."}
    reference = root / "logits-reference"
    for index, folder in enumerate((reference, root / "logits-candidate")):
        _ensure_logit_disk(context, result)
        run_id = uuid.uuid4().hex
        args = list(context["logit_command"]) + [str(context["model_path"]), str(folder), context["backend"],
                "--steps", "16", "--run-id", run_id]
        args += ["--cases", str(fixture_file)] if not index else ["--reference", str(reference)]
        item = _process(context, result, args, "logits-" + str(index + 1))
        metrics_path = folder / "metrics.json"
        if metrics_path.is_file():
            metrics = _json_loads(metrics_path.read_text(encoding="utf-8"))
            result["evidence"]["logits_" + str(index + 1)] = metrics
            first = validate_logit_metrics(metrics, run_id, comparison=bool(index))
            if first:
                result["evidence"]["first_divergence"] = first
            _require(result, "finite fixed-history rows within numerical gates", first is None, "relative L2 <= 0.001, cosine >= 0.999999, identical top1", first)
        else:
            _require(result, "logits metrics written", False, str(metrics_path), None)
        _check_process(result, item, context["backend"])


def validate_chat(response, expected_regex=_ANSWER):
    if response.get("object") != "chat.completion" or len(response.get("choices", [])) != 1:
        raise ScenarioFailure("invalid chat completion envelope")
    choice, usage = response["choices"][0], response.get("usage", {})
    message = choice.get("message", {})
    content = message.get("content")
    if message.get("role") != "assistant" or not isinstance(content, str) or not content.strip():
        raise ScenarioFailure("empty or invalid assistant response")
    if choice.get("finish_reason") != "stop":
        raise ScenarioFailure("completion did not finish normally (including token-budget exhaustion)")
    if re.search(r"^\s*(?:Error:|Exception:)", content, re.I) or (expected_regex and re.search(expected_regex, content, re.I) is None):
        raise ScenarioFailure("assistant failed semantic fixture: " + content[:300])
    prompt, completion = usage.get("prompt_tokens"), usage.get("completion_tokens")
    if not isinstance(prompt, int) or not isinstance(completion, int) or prompt <= 0 or completion <= 0 or usage.get("total_tokens") != prompt + completion:
        raise ScenarioFailure("invalid token usage accounting")
    return content


def validate_sequence_metrics(metrics, schedule, run_id, references=None):
    """Ensure every reused-session row was compared against its fresh canonical case."""
    first = validate_logit_metrics(metrics, run_id, comparison=True)
    cases = metrics["cases"]
    if len(cases) != len(schedule):
        raise ScenarioFailure("order-sensitive schedule did not execute every case")
    for index, (actual, expected) in enumerate(zip(cases, schedule)):
        for key, value in (("name", expected["name"]), ("reference_case", expected["reference_case"]),
                           ("reference_scope", "external"), ("reset_kv_cache", True), ("session_case_index", index),
                           ("steps", 32)):
            if actual.get(key) != value:
                raise ScenarioFailure("order-sensitive probe evidence mismatch: " + key)
        expected_length = 32 if expected["reference_case"] == "short" else 512
        if actual.get("prompt_tokens") != expected_length:
            raise ScenarioFailure("order-sensitive prompt length mismatch")
        if references is not None:
            reference = references[expected["reference_case"]]
            for key, value in _history_hashes(reference).items():
                if actual.get(key) != value:
                    raise ScenarioFailure("order-sensitive teacher-forced history hash mismatch: " + key)
    return first


def _logits_sequence(case, context, result):
    root = Path(context["artifact_dir"])
    library = root / "reference-library"
    library.mkdir(exist_ok=True)
    canonical = []
    result["inputs"] = {"short_prompt_tokens": 32, "long_prompt_tokens": 512, "decode_steps": 32,
                        "histories": "Each candidate inherits exact prompt/generated IDs from its fresh-process canonical reference.",
                        "orders": ["short-short", "long-long", "short-long-short", "long-short"],
                        "limitation": "Within-backend sequence/reset consistency, not an independent quality oracle."}
    for name, length in (("short", 32), ("long", 512)):
        _ensure_logit_disk(context, result, sequence=True)
        fixtures = [{"name": name, "prompt": "A fixed regression prompt describes a red fox and a blue lake. ", "target_tokens": length}]
        fixture_path = root / (name + "-cases.json")
        fixture_path.write_text(json.dumps(fixtures), encoding="utf-8")
        output = root / ("fresh-" + name)
        run_id = uuid.uuid4().hex
        args = list(context["logit_command"]) + [str(context["model_path"]), str(output), context["backend"],
                "--steps", "32", "--cases", str(fixture_path), "--run-id", run_id]
        item = _process(context, result, args, "fresh-" + name)
        metrics = _json_loads((output / "metrics.json").read_text(encoding="utf-8"))
        result["evidence"]["fresh_" + name] = metrics
        first = validate_logit_metrics(metrics, run_id, comparison=False)
        _require(result, name + " fresh baseline finite", first is None, None, first)
        _check_process(result, item, context["backend"])
        rows = _json_loads((output / "cases.json").read_text(encoding="utf-8"))
        _require(result, name + " baseline exact shape", len(rows) == 1 and rows[0].get("name") == name
                 and len(rows[0].get("prompt_tokens", [])) == length and len(rows[0].get("generated_tokens", [])) == 32)
        for key, expected_hash in _history_hashes(rows[0]).items():
            _require(result, name + " baseline " + key, metrics["cases"][0].get(key) == expected_hash,
                     expected_hash, metrics["cases"][0].get(key))
        # This library joins independent process outputs, never two baselines run in
        # one session. Only the probe's synthetic artifacts are copied.
        shutil.copyfile(output / (name + ".f32"), library / (name + ".f32"))
        canonical.append(rows[0])
    (library / "cases.json").write_text(json.dumps(canonical), encoding="utf-8")
    failures = []
    for order in ("short-short", "long-long", "short-long-short", "long-short"):
        _ensure_logit_disk(context, result, sequence=True)
        sequence = [{"name": f"{name}-{index}", "reference_case": name} for index, name in enumerate(order.split("-"))]
        fixture_path = root / ("sequence-" + order + ".json")
        fixture_path.write_text(json.dumps(sequence), encoding="utf-8")
        output, run_id = root / ("sequence-" + order), uuid.uuid4().hex
        args = list(context["logit_command"]) + [str(context["model_path"]), str(output), context["backend"],
                "--reference", str(library), "--cases", str(fixture_path), "--steps", "32", "--run-id", run_id]
        item = _process(context, result, args, "sequence-" + order)
        try:
            metrics = _json_loads((output / "metrics.json").read_text(encoding="utf-8"))
            result["evidence"].setdefault("sequence_metrics", {})[order] = metrics
            references = {entry["name"]: entry for entry in canonical}
            first = validate_sequence_metrics(metrics, sequence, run_id, references)
            if first:
                divergence = {"schedule": order, **first}
                reference_name = next(entry["reference_case"] for entry in sequence if entry["name"] == first["case"])
                reference = references[reference_name]
                divergence["reference_case"] = reference_name
                divergence["input_history_sha256"] = _token_hash(reference["prompt_tokens"] + reference["generated_tokens"][:first["step"]])
                result["evidence"].setdefault("divergences", []).append(divergence)
                result["evidence"].setdefault("first_divergence", divergence)
            _require(result, order + " reset history numerical parity", first is None,
                     "fresh-reference L2<=0.001 cosine>=0.999999 top1 identical", first)
            _check_process(result, item, context["backend"])
        except (ScenarioFailure, OSError, ValueError) as error:
            failures.append({"schedule": order, "reason": str(error)})
    if failures:
        result["evidence"]["failed_schedules"] = failures
        raise ScenarioFailure("order-sensitive fixed-history failures: " + ", ".join(x["schedule"] for x in failures))


def validate_embeddings(response, dimensions):
    rows = response.get("data", [])
    if response.get("object") != "list" or len(rows) != 4:
        raise ScenarioFailure("embedding response must contain exactly four indexed vectors")
    vectors = []
    for i, row in enumerate(rows):
        vector = row.get("embedding", [])
        if row.get("index") != i or len(vector) != dimensions or dimensions < 1:
            raise ScenarioFailure("embedding index/dimension mismatch")
        if not all(isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x) for x in vector):
            raise ScenarioFailure("nonfinite embedding")
        norm = math.sqrt(sum(x * x for x in vector))
        if abs(norm - 1) > 0.02:
            raise ScenarioFailure("embedding is zero or not normalized")
        vectors.append([x / norm for x in vector])
    cosine = lambda a, b: sum(x * y for x, y in zip(a, b))
    same, related, unrelated = (cosine(vectors[0], vectors[i]) for i in (1, 2, 3))
    if same < 0.99999 or unrelated >= same - 1e-5 or related <= unrelated + 1e-4:
        raise ScenarioFailure("embedding duplicate consistency or semantic relevance ordering failed")
    return {"dimensions": dimensions, "duplicate_cosine": same, "related_cosine": related, "unrelated_cosine": unrelated}


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        # A loopback server must never redirect a regression request (and its
        # synthetic request body) to another origin or unrelated local service.
        return None


class _Http:
    def __init__(self, port, deadline, result):
        self.base, self.deadline, self.result = "http://127.0.0.1:" + str(port), deadline, result
        self.opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), _NoRedirect())

    def remaining(self):
        seconds = self.deadline - time.monotonic()
        if seconds <= 0:
            raise ScenarioFailure("server scenario deadline exceeded")
        return seconds

    def open(self, route, payload=None, method=None):
        if not route.startswith("/") or route.startswith("//"):
            raise ScenarioFailure("nonlocal HTTP route refused")
        self.result["inputs"].setdefault("requests", []).append({"route": route, "method": method or ("POST" if payload is not None else "GET"), "body": payload})
        data = None if payload is None else json.dumps(payload, allow_nan=False).encode("utf-8")
        request = urllib.request.Request(self.base + route, data=data, method=method,
                                         headers={"Content-Type": "application/json"})
        try:
            return self.opener.open(request, timeout=self.remaining())
        except urllib.error.HTTPError as error:
            self.result["evidence"].setdefault("http_errors", []).append({"route": route, "status": error.code,
                "body": error.read(64 * 1024).decode("utf-8", "replace")})
            error.close()
            raise

    def json(self, route, payload=None, method=None):
        started = time.monotonic()
        with self.open(route, payload, method) as response:
            status = response.status
            body = response.read(4 * 1024 * 1024 + 1)
            if len(body) > 4 * 1024 * 1024:
                raise ScenarioFailure("HTTP response exceeded capture budget")
        value = _json_loads(body)
        self.result["evidence"].setdefault("responses", []).append({"route": route, "status": status,
            "duration_seconds": round(time.monotonic() - started, 4), "body": value})
        return value

    def stream(self, route, payload, *, cancel=False, web_ui=False):
        started = time.monotonic()
        chunks, content, finish, usage, done = [], "", None, None, False
        with self.open(route, payload) as response:
            if "text/event-stream" not in response.headers.get("Content-Type", ""):
                raise ScenarioFailure("stream is not text/event-stream")
            size = 0
            while True:
                self.remaining()
                raw = response.readline(1024 * 1024 + 1)
                size += len(raw)
                if size > 4 * 1024 * 1024 or len(raw) > 1024 * 1024:
                    raise ScenarioFailure("SSE capture budget exceeded")
                if not raw:
                    break
                line = raw.decode("utf-8").strip()
                if not line.startswith("data:"):
                    continue
                data = line[5:].strip()
                if done:
                    raise ScenarioFailure("stream emitted data after its terminal event")
                if data == "[DONE]":
                    done = True
                    continue
                event = _json_loads(data)
                chunks.append(event)
                if event.get("error"):
                    raise ScenarioFailure("server stream error: " + str(event["error"]))
                if web_ui:
                    if isinstance(event.get("replace"), str):
                        content = event["replace"]
                    else:
                        content += str(event.get("token", ""))
                    if event.get("done"):
                        if event.get("aborted") or event.get("truncated"):
                            raise ScenarioFailure("web UI request aborted or exhausted the token budget")
                        done, usage = True, event
                        continue
                else:
                    if event.get("object") != "chat.completion.chunk":
                        raise ScenarioFailure("invalid streaming completion envelope")
                    for choice in event.get("choices", []):
                        delta = choice.get("delta", {})
                        content += delta.get("content") or ""
                        if choice.get("finish_reason"):
                            finish = choice["finish_reason"]
                        if cancel and (delta.get("content") or delta.get("reasoning_content")):
                            queue = self.json("/api/queue/status")
                            if queue.get("processing", 0) <= 0:
                                raise ScenarioUntested("stream produced a token but completed before disconnect; no in-flight cancellation was observed")
                            self.result["evidence"]["cancelled_after_chunk"] = event
                            self.result["evidence"]["queue_before_disconnect"] = queue
                            return {"cancelled": True, "chunks": chunks}
                    usage = event.get("usage") or usage
        answer = {"content": content, "finish_reason": finish, "usage": usage, "done": done, "chunks": chunks,
                  "route": route, "duration_seconds": round(time.monotonic() - started, 4)}
        self.result["evidence"].setdefault("streams", []).append(answer)
        if cancel:
            raise ScenarioFailure("stream completed without observing a cancellable generated chunk")
        if not done or not content or re.search(r"^\s*Error:", content, re.I):
            raise ScenarioFailure("stream is incomplete, empty, or contains an error")
        if not web_ui and finish != "stop":
            raise ScenarioFailure("stream has no normal terminal finish reason")
        if not usage or (not web_ui and usage.get("completion_tokens", 0) <= 0) or (web_ui and (usage.get("promptTokens", 0) <= 0 or usage.get("tokenCount", 0) <= 0)):
            raise ScenarioFailure("stream has no completion usage")
        return answer


def _server(case, context, result):
    kind = _kind(case)
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        port = sock.getsockname()[1]
    command = list(context["server_command"]) + _base_args(context, kind)
    command += ["--host", "127.0.0.1", "--port", str(port), "--no-webui", "--no-multi-agent"]
    if kind == "server_embeddings":
        command += ["--embeddings"]
    process = ManagedProcess(command, cwd=context["repo"], artifact_dir=context["artifact_dir"], stage="server", env=context.get("env"))
    deadline = time.monotonic() + context.get("timeout_seconds", 600)
    http = _Http(port, deadline, result)
    result["evidence"]["base_url"] = http.base
    try:
        # Require this child to have bound its listener before contacting the ephemeral
        # address; do not accidentally test an unrelated process in a bind race.
        while True:
            if process.process.poll() is not None:
                raise ScenarioFailure("server exited before readiness")
            http.remaining()
            startup_out, _ = process.stdout.read()
            startup_err, _ = process.stderr.read()
            if f"Now listening on: {http.base}" in startup_out + startup_err:
                break
            time.sleep(0.1)
        identity = http.json("/api/models")
        _require(result, "loaded backend identity", identity.get("loadedBackend") == context["backend"], context["backend"], identity.get("loadedBackend"))
        _require(result, "loaded model identity", identity.get("loaded") == Path(context["model_path"]).name, Path(context["model_path"]).name, identity.get("loaded"))
        listing = http.json("/v1/models").get("data", [])
        _require(result, "one hosted model advertised", len(listing) == 1 and bool(listing[0].get("id")))
        model = listing[0]["id"]
        payload = {"model": model, "messages": [{"role": "user", "content": _PROMPT}], "temperature": 0,
                   "seed": 42, "max_tokens": 128, "think": False, "stream": False}
        if kind == "server_embeddings":
            response = http.json("/v1/embeddings", {"model": model, "input": ["A cat is sitting on a warm windowsill.",
                "A cat is sitting on a warm windowsill.", "A kitten rests beside the sunny window.",
                "Database transactions must satisfy atomicity and isolation."], "encoding_format": "float"})
            checks = validate_embeddings(response, listing[0].get("embedding_dimensions", 0))
            result["evidence"]["embedding_checks"] = checks
            _require(result, "finite normalized input-sensitive embeddings", True, "unit vectors and duplicate consistency", checks)
        elif kind == "server_structured":
            payload["response_format"] = {"type": "json_schema", "json_schema": {"name": "answer", "strict": True,
                "schema": {"type": "object", "properties": {"answer": {"type": "integer"}}, "required": ["answer"], "additionalProperties": False}}}
            payload["messages"][0]["content"] = "What is 7 multiplied by 8? Return a JSON object with the integer field answer."
            response = http.json("/v1/chat/completions", payload)
            answer = _json_loads(validate_chat(response, None))
            _require(result, "strict structured semantic result", answer == {"answer": 56} and type(answer.get("answer")) is int, {"answer": 56}, answer)
        elif kind == "server_tools":
            payload["messages"][0]["content"] = "Call get_regression_value with key fixture. Do not answer until you receive its value."
            payload["tools"] = [{"type": "function", "function": _TOOL}]
            payload["tool_choice"] = {"type": "function", "function": {"name": _TOOL["name"]}}
            response = http.json("/v1/chat/completions", payload)
            choice = response.get("choices", [{}])[0]
            calls = choice.get("message", {}).get("tool_calls", [])
            _require(result, "client tool call envelope", response.get("object") == "chat.completion" and
                     choice.get("message", {}).get("role") == "assistant" and choice.get("finish_reason") == "tool_calls" and len(calls) == 1,
                     "one assistant tool_calls finish", choice)
            call = calls[0]
            _require(result, "client tool identity", call.get("function", {}).get("name") == _TOOL["name"] and bool(call.get("id")))
            arguments = _json_loads(call["function"]["arguments"])
            _require(result, "client tool arguments", arguments == {"key": "fixture"}, {"key": "fixture"}, arguments)
            payload["messages"] += [choice["message"], {"role": "tool", "tool_call_id": call["id"], "content": '{"value":56}'},
                                     {"role": "user", "content": "Reply with only the integer value returned by the tool."}]
            payload["tool_choice"] = "none"
            validate_chat(http.json("/v1/chat/completions", payload))
            _require(result, "fixed synthetic tool-result round trip", True)
            result["evidence"]["limitation"] = "No model-generated function, shell command, skill, or host agent was executed."
        elif kind == "server_cancel":
            long_payload = dict(payload, stream=True, max_tokens=512,
                                messages=[{"role": "user", "content": "Count from 1 to 200, one number per line. Do not stop before 200."}])
            http.stream("/v1/chat/completions", long_payload, cancel=True)
            while True:
                queue = http.json("/api/queue/status")
                if queue.get("processing") == 0 and queue.get("pending_requests") == 0:
                    break
                time.sleep(min(0.1, http.remaining()))
            validate_chat(http.json("/v1/chat/completions", payload))
            _require(result, "disconnect cancellation drains queue and recovers", True)
        elif kind == "server_reset_cache":
            _reset_and_cache(http, payload, result)
        else:
            first = validate_chat(http.json("/v1/chat/completions", payload))
            if kind == "server_stream":
                streamed = http.stream("/v1/chat/completions", dict(payload, stream=True))
                _require(result, "stream and nonstream content parity", streamed["content"] == first, first, streamed["content"])
                usage = streamed["usage"]
                _require(result, "stream token accounting", usage.get("total_tokens") == usage.get("prompt_tokens", 0) + usage.get("completion_tokens", 0))
            else:
                second = validate_chat(http.json("/v1/chat/completions", payload))
                _require(result, "server greedy replay", second == first, first, second)
    finally:
        process.stop()
        item = process.snapshot()
        result["processes"].append({k: v for k, v in item.items() if k not in {"stdout", "stderr"}})
        # An intentional server shutdown is not a model test failure; readiness,
        # model identity and each request above carry their own assertions.
        result["evidence"]["server_shutdown"] = "owned process tree terminated after scenario"


def _reset_and_cache(http, payload, result):
    session = http.json("/api/sessions", {})["sessionId"]
    route = "/api/sessions/" + urllib.parse.quote(session, safe="")
    try:
        chat = {"sessionId": session, "messages": [{"role": "user", "content": _PROMPT}],
                "maxTokens": 128, "temperature": 0, "seed": 42, "think": False, "newChat": True}
        first = http.stream("/api/chat", chat, web_ui=True)["content"]
        second = http.stream("/api/chat", chat, web_ui=True)["content"]
        _require(result, "newChat reset answer equivalence", first == second and re.search(_ANSWER, second) is not None, first, second)
    finally:
        deleted = http.json(route, method="DELETE")
        _require(result, "session disposed", deleted.get("ok") is True)
    try:
        http.json(route, method="DELETE")
    except urllib.error.HTTPError as error:
        _require(result, "disposed session no longer exists", error.code == 404, 404, error.code)
    else:
        _require(result, "disposed session no longer exists", False, 404, 200)
    prefix = "The following is a synthetic cache fixture, with no private information. " * 40
    repeated = dict(payload, messages=[{"role": "user", "content": prefix + "\n" + _PROMPT}])
    first_response = http.json("/v1/chat/completions", repeated)
    first = validate_chat(first_response)
    second_response = http.json("/v1/chat/completions", repeated)
    second = validate_chat(second_response)
    _require(result, "cached prefix preserves answer", first == second, first, second)
    reused = second_response.get("usage", {}).get("prompt_tokens_details", {}).get("cached_tokens", 0)
    result["evidence"]["cached_tokens"] = reused
    if reused <= 0:
        raise ScenarioUntested("reset and replay assertions passed, but no positive prefix-cache hit was observed; cache coverage remains untested")
    _require(result, "prefix-cache hit observed", True, ">0 cached_tokens", reused)


def run_scenario(case, context):
    """Execute one adapter; status is pass/fail/untested, never infer coverage from exit 0."""
    start = time.monotonic()
    root = Path(context["artifact_dir"])
    root.mkdir(parents=True, exist_ok=True)
    result = {"id": case.get("id", _kind(case)), "kind": _kind(case), "status": "untested", "reason": "",
              "assertions": [], "inputs": {}, "evidence": {}, "processes": []}
    available, reason = availability(case, context)
    if not available:
        result["reason"] = reason
        return result
    interrupted = False
    try:
        kind = _kind(case)
        if kind == "forced_logits_sequence":
            _logits_sequence(case, context, result)
        elif kind == "forced_logits":
            _logits(case, context, result)
        elif kind.startswith("cli_"):
            _cli(case, context, result)
        else:
            _server(case, context, result)
        result["status"] = "pass"
        result["reason"] = "all scenario-specific assertions passed"
    except ScenarioUntested as error:
        result["reason"] = str(error)
    except KeyboardInterrupt:
        interrupted = True
        result["reason"] = "cancelled by user; owned process tree terminated; scenario remains untested"
    except (ScenarioFailure, OSError, ValueError, KeyError, TypeError, IndexError) as error:
        result["status"], result["reason"] = "fail", type(error).__name__ + ": " + str(error)
    finally:
        result["duration_seconds"] = round(time.monotonic() - start, 4)
    # Synthetic fixtures are the only inputs, and env values are not exported. Still
    # sanitize known credentials in unexpected errors/logs before saving diagnostics.
    encoded = redact(json.dumps(_finite_json(result), ensure_ascii=False, allow_nan=False, indent=2), secret_values())
    result = json.loads(encoded)
    (root / "scenario.json").write_text(encoded + "\n", encoding="utf-8")
    if interrupted:
        raise KeyboardInterrupt
    return result

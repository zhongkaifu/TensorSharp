        private static string Ggml(GraphOpSchemaModel m)
        {
            var w = new Writer();
            w.Raw(Banner);
            w.Line("namespace TensorSharp.GGML");
            w.Open();
            w.Doc("Op codes of the generic GGML graph (TsgGraphOp in tsg_graph_ops.g.h, TensorSharp.Graph.GraphOp): all three are generated from " + SchemaPath + ".");
            w.Line("public enum GgmlGraphOp");
            w.Open();
            foreach (GraphOpDefinition op in m.Ops)
            {
                w.Doc($"<see cref=\"TensorSharp.Graph.GraphOp.{op.Name}\"/> ({op.Native}).");
                w.Line($"{op.Name} = {op.Code},");
            }
            w.Close();
            w.Close();
            return w.ToString();
        }

        // ---------------------------------------------------------------- C++: the native bridge

        private static string Native(GraphOpSchemaModel m)
        {
            var sb = new StringBuilder();
            sb.Append(Banner);
            sb.Append("#pragma once\n\n#include <cstdint>\n#include <string>\n\n");
            sb.Append("// The graph op protocol shared with TensorSharp.Graph.GraphOp and TensorSharp.GGML.GgmlGraphOp.\n");
            sb.Append("namespace tsg { namespace graph_schema {\n\n");
            sb.Append($"constexpr int kVersion = {m.Version};\n");
            sb.Append($"constexpr const char* kHash = \"{m.Hash}\";\n\n");
            sb.Append("enum TsgGraphOp : int\n{\n");
            foreach (GraphOpDefinition op in m.Ops)
            {
                string comment = NativeComment(op);
                sb.Append($"    {op.Native} = {op.Code},");
                if (comment.Length > 0) sb.Append(' ', Math.Max(1, 28 - op.Native.Length - op.Code.ToString(CultureInfo.InvariantCulture).Length)).Append("// ").Append(comment);
                sb.Append('\n');
            }
            sb.Append("};\n\n");
            sb.Append("struct OpSignature\n{\n    const char* name;\n    int srcs_min, srcs_max, ip_min, ip_max, fp_min, fp_max;\n};\n\n");
            sb.Append("// The schema's signature of `op`, or null for a code that is not an op of the schema.\n");
            sb.Append("inline const OpSignature* signature(int op)\n{\n    switch (op)\n    {\n");
            foreach (GraphOpDefinition op in m.Ops)
            {
                sb.Append($"    case {op.Native}: {{ static const OpSignature s{{ \"{op.Name}\", {op.Srcs.Min}, {op.Srcs.Max}, {op.Ip.Min}, {op.Ip.Max}, {op.Fp.Min}, {op.Fp.Max} }}; return &s; }}\n");
            }
            sb.Append("    default: return nullptr;\n    }\n}\n\n");
            sb.Append("// Empty when an op of these counts fits the schema, else why not (checked as each op is recorded).\n");
            sb.Append("inline std::string check(int op, int nsrc, int nip, int nfp)\n{\n");
            sb.Append("    const OpSignature* s = signature(op);\n");
            sb.Append("    if (s == nullptr) return \"graph builder: unknown op \" + std::to_string(op);\n");
            sb.Append("    auto bad = [&](const char* what, int n, int lo, int hi) {\n");
            sb.Append("        return std::string(\"graph builder: \") + s->name + \" takes \" + std::to_string(lo) + (lo == hi ? \"\" : \"..\" + std::to_string(hi)) + \" \" + what\n");
            sb.Append("            + \", the program gave \" + std::to_string(n);\n    };\n");
            sb.Append("    if (nsrc < s->srcs_min || nsrc > s->srcs_max) return bad(\"operands\", nsrc, s->srcs_min, s->srcs_max);\n");
            sb.Append("    if (nip < s->ip_min || nip > s->ip_max) return bad(\"integer parameters\", nip, s->ip_min, s->ip_max);\n");
            sb.Append("    if (nfp < s->fp_min || nfp > s->fp_max) return bad(\"float parameters\", nfp, s->fp_min, s->fp_max);\n");
            sb.Append("    return std::string();\n}\n\n");

            sb.Append("// Operand and parameter slots of each op (GraphOpParams in C#): slots::rope_ext::IP_N_DIMS and so on.\n");
            sb.Append("namespace slots {\n");
            foreach (GraphOpDefinition op in m.Ops)
            {
                if (op.Ip.Slots.Count == 0 && op.Fp.Slots.Count == 0 && op.Srcs.Slots.Count <= 1) continue;
                sb.Append($"namespace {Snake(op.Name)} {{\n");
                for (int i = 0; i < op.Srcs.Slots.Count && op.Srcs.Slots.Count > 1; i++)
                    sb.Append($"constexpr int SRC_{Upper(op.Srcs.Slots[i].Name)} = {i};\n");
                for (int i = 0; i < op.Ip.Slots.Count; i++)
                {
                    GraphSlot s = op.Ip.Slots[i];
                    sb.Append($"constexpr int IP_{Upper(s.Name)} = {i};");
                    if (s.Default != null) sb.Append($" constexpr std::int64_t IP_{Upper(s.Name)}_DEFAULT = {CsLong(s.Default)};");
                    sb.Append('\n');
                }
                for (int i = 0; i < op.Fp.Slots.Count; i++)
                {
                    GraphSlot s = op.Fp.Slots[i];
                    sb.Append($"constexpr int FP_{Upper(s.Name)} = {i};");
                    if (s.Default != null) sb.Append($" constexpr float FP_{Upper(s.Name)}_DEFAULT = {CppFloat(s.Default)};");
                    sb.Append('\n');
                }
                sb.Append("}\n");
            }
            sb.Append("} // namespace slots\n");
            sb.Append("\n} } // namespace tsg::graph_schema\n");
            return sb.ToString();
        }

        private static string NativeComment(GraphOpDefinition op)
        {
            var parts = new List<string>();
            if (op.Srcs.Slots.Count > 1 || op.Srcs.Variadic || op.Srcs.Slots.Any(s => s.Optional))
                parts.Add("srcs: " + Names(op.Srcs));
            if (op.Ip.Slots.Count > 0) parts.Add("ip: " + Names(op.Ip));
            if (op.Fp.Slots.Count > 0) parts.Add("fp: " + Names(op.Fp));
            return string.Join("; ", parts);
        }

        private static string Names(GraphSlotList l)
        {
            string s = string.Join(", ", l.Slots.Select((x, i) => i >= l.Min ? $"[{Snake(x.Name)}]" : Snake(x.Name)));
            return l.Variadic ? s + ", ..." : s;
        }


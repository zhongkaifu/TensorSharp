        private static string OpDoc(GraphOpDefinition op)
        {
            string doc = op.Doc.Length > 0 ? op.Doc : op.Name + ".";
            var parts = new List<string>();
            if (op.Srcs.Slots.Count > 0) parts.Add("operands " + Names(op.Srcs));
            if (op.Ip.Slots.Count > 0) parts.Add("ip " + Names(op.Ip));
            if (op.Fp.Slots.Count > 0) parts.Add("fp " + Names(op.Fp));
            if (parts.Count == 0) return doc;
            string joined = string.Join("; ", parts);
            return joined.Contains('[') ? $"{doc} Schema: {joined} (bracketed slots may be left out)." : $"{doc} Schema: {joined}.";
        }

        private static string Literal(string kind, string v)
        {
            if (kind == "fp") return CsFloat(v);
            return CsLong(v);
        }

        private static string CsFloat(string v) => v switch
        {
            "inf" or "+inf" => "float.PositiveInfinity",
            "-inf" => "float.NegativeInfinity",
            _ => float.Parse(v, NumberStyles.Float, CultureInfo.InvariantCulture).ToString("R", CultureInfo.InvariantCulture) + "f",
        };

        private static string CppFloat(string v) => v switch
        {
            "inf" or "+inf" => "INFINITY",
            "-inf" => "-INFINITY",
            _ => FloatLiteral(float.Parse(v, NumberStyles.Float, CultureInfo.InvariantCulture)),
        };

        private static string FloatLiteral(float f)
        {
            string s = f.ToString("R", CultureInfo.InvariantCulture);
            if (!s.Contains('.') && !s.Contains('E') && !s.Contains('e')) s += ".0";
            return s + "f";
        }

        private static string CsLong(string v) => long.Parse(v, NumberStyles.Integer, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture);

        private static string Pascal(string name) => char.ToUpperInvariant(name[0]) + name[1..];

        private static string Camel(string name) => char.ToLowerInvariant(name[0]) + name[1..];

        private static readonly HashSet<string> s_keywords = new(StringComparer.Ordinal) { "in", "out", "ref", "base", "default", "params", "checked", "fixed", "object", "string", "event", "operator" };

        private static string Arg(string name)
        {
            string c = Camel(name);
            return s_keywords.Contains(c) ? "@" + c : c;
        }

        private static string Snake(string name)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < name.Length; i++)
            {
                char c = name[i];
                if (char.IsUpper(c) && i > 0 && (char.IsLower(name[i - 1]) || (i + 1 < name.Length && char.IsLower(name[i + 1]) && char.IsUpper(name[i - 1]))))
                    sb.Append('_');
                else if (char.IsDigit(c) && i > 0 && char.IsLetter(name[i - 1]))
                    sb.Append('_');
                sb.Append(char.ToLowerInvariant(c));
            }
            return sb.ToString();
        }

        private static string Upper(string name) => Snake(name).ToUpperInvariant();

        private sealed class Writer
        {
            private readonly StringBuilder _sb = new();
            public int Indent;

            public void Raw(string s) => _sb.Append(s);

            public void Line(string s = "", int delta = 0)
            {
                if (s.Length == 0) { _sb.Append('\n'); return; }
                _sb.Append(' ', 4 * Math.Max(0, Indent + delta)).Append(s).Append('\n');
            }

            public void Open() { Line("{"); Indent++; }

            public void Close() { Indent--; Line("}"); }

            public void Doc(string text)
            {
                foreach (string l in Wrap(text, 116 - 4 * Indent))
                    Line("/// " + l);
            }

            private static IEnumerable<string> Wrap(string text, int width)
            {
                string[] words = ("<summary>" + text + "</summary>").Split(' ', StringSplitOptions.RemoveEmptyEntries);
                var line = new StringBuilder();
                foreach (string word in words)
                {
                    if (line.Length > 0 && line.Length + 1 + word.Length > width)
                    {
                        yield return line.ToString();
                        line.Clear();
                    }
                    if (line.Length > 0) line.Append(' ');
                    line.Append(word);
                }
                if (line.Length > 0) yield return line.ToString();
            }

            public override string ToString() => _sb.ToString();
        }
    }

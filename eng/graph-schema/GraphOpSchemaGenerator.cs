    /// <summary>One operand or parameter slot of an op: its name and, for a parameter the executors fall back on, its default.</summary>
    public sealed record GraphSlot(string Name, string? Default, bool Optional);

    /// <summary>An op's operands, integer parameters or float parameters: how many every program carries (Min), how many an
    /// executor reads (Max), and the slots in order.</summary>
    public sealed record GraphSlotList(int Min, int Max, IReadOnlyList<GraphSlot> Slots)
    {
        public static readonly GraphSlotList Empty = new(0, 0, Array.Empty<GraphSlot>());
        public bool Variadic => Max > Slots.Count;
    }

    public sealed record GraphOpDefinition(string Name, int Code, string Native, GraphSlotList Srcs, GraphSlotList Ip, GraphSlotList Fp, string Doc);

    public sealed record GraphOpSchemaModel(int Version, IReadOnlyList<GraphOpDefinition> Ops)
    {
        /// <summary>The ABI hash: SHA-256 over the canonical structure (codes, names, native names, operand and parameter
        /// slots, their bounds and defaults, the version), first 16 hex digits. Docs are not part of it.</summary>
        public string Hash => GraphOpSchemaGenerator.ComputeHash(this);
    }

    /// <summary>
    /// Reads TensorSharp.Core/Graph/Schema/graph-ops.json and generates the three definitions of the graph op protocol from it:
    /// the IR's <c>GraphOp</c> (with its schema table, parameter slot constants and typed emitters), the GGML managed bridge's
    /// <c>GgmlGraphOp</c> and the native bridge's <c>TsgGraphOp</c> (tsg_graph_ops.g.h). Run by eng/graph-schema
    /// (<c>dotnet run --project eng/graph-schema</c>) and by GraphOpSchemaTests, which fails while a committed file is stale.
    /// </summary>
    public static class GraphOpSchemaGenerator
    {
        public const string SchemaPath = "TensorSharp.Core/Graph/Schema/graph-ops.json";
        public const string ManagedPath = "TensorSharp.Core/Graph/GraphOp.g.cs";
        public const string GgmlPath = "TensorSharp.Backends.GGML/GgmlGraphOp.g.cs";
        public const string NativePath = "TensorSharp.GGML.Native/tsg_graph_ops.g.h";

        private const string Banner = "// <auto-generated>\n// Generated from " + SchemaPath + " by eng/graph-schema (dotnet run --project eng/graph-schema).\n// Do not edit: change the schema and regenerate. GraphOpSchemaTests fails while this file is stale.\n// </auto-generated>\n";

        public static GraphOpSchemaModel Parse(string json)
        {
            using JsonDocument doc = JsonDocument.Parse(json, new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip, AllowTrailingCommas = true });
            JsonElement root = doc.RootElement;
            int version = root.GetProperty("version").GetInt32();
            var ops = new List<GraphOpDefinition>();
            var names = new HashSet<string>(StringComparer.Ordinal);
            var natives = new HashSet<string>(StringComparer.Ordinal);
            var codes = new HashSet<int>();
            foreach (JsonElement e in root.GetProperty("ops").EnumerateArray())
            {
                string name = e.GetProperty("name").GetString() ?? throw new FormatException("an op without a name");
                int code = e.GetProperty("code").GetInt32();
                string native = e.GetProperty("native").GetString() ?? throw new FormatException($"{name}: no native name");
                if (!names.Add(name)) throw new FormatException($"op {name} is defined twice");
                if (!natives.Add(native)) throw new FormatException($"native name {native} is used twice");
                if (!codes.Add(code)) throw new FormatException($"op code {code} is used twice ({name})");
                if (code <= 0 || code > 255) throw new FormatException($"{name}: op code {code} outside 1..255");
                GraphSlotList srcs = ParseSrcs(name, e.TryGetProperty("srcs", out JsonElement s) ? s : default);
                GraphSlotList ip = ParseParams(name, "ip", e.TryGetProperty("ip", out JsonElement i) ? i : default);
                GraphSlotList fp = ParseParams(name, "fp", e.TryGetProperty("fp", out JsonElement f) ? f : default);
                string docText = e.TryGetProperty("doc", out JsonElement d) ? d.GetString() ?? "" : "";
                ops.Add(new GraphOpDefinition(name, code, native, srcs, ip, fp, docText));
            }
            return new GraphOpSchemaModel(version, ops);
        }

        private static GraphSlotList ParseSrcs(string op, JsonElement e)
        {
            if (e.ValueKind == JsonValueKind.Undefined) return GraphSlotList.Empty;
            JsonElement names = e;
            int? min = null, max = null;
            if (e.ValueKind == JsonValueKind.Object)
            {
                names = e.GetProperty("names");
                if (e.TryGetProperty("min", out JsonElement mn)) min = mn.GetInt32();
                if (e.TryGetProperty("max", out JsonElement mx)) max = mx.GetInt32();
            }
            var slots = new List<GraphSlot>();
            bool optionalSeen = false;
            foreach (JsonElement n in names.EnumerateArray())
            {
                string raw = n.GetString() ?? throw new FormatException($"{op}: an unnamed operand");
                bool optional = raw.EndsWith('?');
                string name = optional ? raw[..^1] : raw;
                if (!optional && optionalSeen) throw new FormatException($"{op}: required operand {name} after an optional one");
                optionalSeen |= optional;
                slots.Add(new GraphSlot(name, null, optional));
            }
            int required = slots.Count(x => !x.Optional);
            var list = new GraphSlotList(min ?? required, max ?? slots.Count, slots);
            Check(op, "srcs", list);
            return list;
        }

        private static GraphSlotList ParseParams(string op, string kind, JsonElement e)
        {
            if (e.ValueKind == JsonValueKind.Undefined) return GraphSlotList.Empty;
            var slots = new List<GraphSlot>();
            foreach (JsonElement n in e.GetProperty("slots").EnumerateArray())
            {
                string raw = n.GetString() ?? throw new FormatException($"{op}: an unnamed {kind} slot");
                int eq = raw.IndexOf('=');
                string name = eq < 0 ? raw : raw[..eq];
                string? def = eq < 0 ? null : raw[(eq + 1)..];
                if (def != null) _ = Literal(kind, def);   // validates the default
                slots.Add(new GraphSlot(name, def, false));
            }
            int min = e.TryGetProperty("min", out JsonElement mn) ? mn.GetInt32() : 0;
            int max = e.TryGetProperty("max", out JsonElement mx) ? mx.GetInt32() : slots.Count;
            var list = new GraphSlotList(min, max, slots);
            Check(op, kind, list);
            return list;
        }

        private static void Check(string op, string kind, GraphSlotList list)
        {
            if (list.Min < 0 || list.Min > list.Max || list.Max > 64)
                throw new FormatException($"{op}: {kind} bounds {list.Min}..{list.Max} are invalid");
            if (list.Min > list.Slots.Count) throw new FormatException($"{op}: {kind} requires {list.Min} but names {list.Slots.Count}");
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            foreach (GraphSlot s in list.Slots)
            {
                if (s.Name.Length == 0 || !char.IsLetter(s.Name[0]) || !s.Name.All(char.IsLetterOrDigit))
                    throw new FormatException($"{op}: {kind} slot name '{s.Name}' is not an identifier");
                if (!seen.Add(s.Name)) throw new FormatException($"{op}: {kind} slot {s.Name} named twice");
            }
        }

        internal static string ComputeHash(GraphOpSchemaModel m)
        {
            var sb = new StringBuilder();
            sb.Append("tsg-graph-ops/").Append(m.Version).Append('\n');
            foreach (GraphOpDefinition op in m.Ops.OrderBy(o => o.Code))
            {
                sb.Append(op.Code).Append(' ').Append(op.Name).Append(' ').Append(op.Native);
                Canon(sb, "s", op.Srcs);
                Canon(sb, "i", op.Ip);
                Canon(sb, "f", op.Fp);
                sb.Append('\n');
            }
            byte[] digest = SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString()));
            return Convert.ToHexString(digest, 0, 8).ToLowerInvariant();
        }

        private static void Canon(StringBuilder sb, string tag, GraphSlotList l)
        {
            sb.Append(' ').Append(tag).Append(l.Min).Append('-').Append(l.Max).Append('[');
            sb.Append(string.Join(",", l.Slots.Select(s => s.Name + (s.Optional ? "?" : "") + (s.Default != null ? "=" + s.Default : ""))));
            sb.Append(']');
        }

        /// <summary>Every generated file, by its path relative to the repository root.</summary>
        public static IReadOnlyDictionary<string, string> Generate(GraphOpSchemaModel m) => new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [ManagedPath] = Managed(m),
            [GgmlPath] = Ggml(m),
            [NativePath] = Native(m),
        };

        // ---------------------------------------------------------------- C#: the IR

        private static string Managed(GraphOpSchemaModel m)
        {
            var w = new Writer();
            w.Raw(Banner);
            w.Line("#nullable enable");
            w.Line("using System;");
            w.Line();
            w.Line("namespace TensorSharp.Graph");
            w.Open();
            w.Doc("The operations of a backend-neutral graph program. Each backend's executor plugin lowers them (see <see cref=\"IGraphExecutor\"/>); the parameters follow ggml's semantics, which the models were written against (extents innermost first, byte strides, NeoX / multi-axis rotary modes). The operands and parameters of each op are defined once, in " + SchemaPath + ": <see cref=\"GraphOpSchema\"/> holds its table, <see cref=\"GraphOpParams\"/> its slots and <see cref=\"GraphOpEmit\"/> its typed emitters.");
            w.Line("public enum GraphOp");
            w.Open();
            foreach (GraphOpDefinition op in m.Ops)
            {
                w.Doc(OpDoc(op));
                w.Line($"{op.Name} = {op.Code},");
            }
            w.Close();
            w.Line();

            // The signature record and the table.
            w.Doc("An op's structure as the schema defines it: how many operands, integer and float parameters every program carries (Min) and how many an executor reads (Max).");
            w.Line("public readonly record struct GraphOpSignature(GraphOp Op, int SrcsMin, int SrcsMax, int IpMin, int IpMax, int FpMin, int FpMax);");
            w.Line();
            w.Doc("The graph op protocol's schema table (generated from " + SchemaPath + "). <see cref=\"GraphProgramBuilder.Op\"/> checks every op against it as it is recorded, so a program with a missing operand or parameter is refused when it is built, not when an executor reads past its arrays.");
            w.Line("public static class GraphOpSchema");
            w.Open();
            w.Doc("Bumped when an op's meaning changes without a change to its structure.");
            w.Line($"public const int Version = {m.Version};");
            w.Doc("The ABI hash of the schema's structure (codes, names, slots, bounds, defaults): the native bridge reports its own (TSGgml_GraphSchemaHash), and a mismatch is refused when the GGML backend initializes.");
            w.Line($"public const string Hash = \"{m.Hash}\";");
            w.Line();
            int maxCode = m.Ops.Max(o => o.Code);
            w.Line($"private static readonly GraphOpSignature[] s_signatures = new GraphOpSignature[{maxCode + 1}];");
            w.Line();
            w.Line("static GraphOpSchema()");
            w.Open();
            foreach (GraphOpDefinition op in m.Ops)
                w.Line($"s_signatures[{op.Code}] = new GraphOpSignature(GraphOp.{op.Name}, {op.Srcs.Min}, {op.Srcs.Max}, {op.Ip.Min}, {op.Ip.Max}, {op.Fp.Min}, {op.Fp.Max});");
            w.Close();
            w.Line();
            w.Doc("Every op of the schema, in code order.");
            w.Line("public static ReadOnlySpan<GraphOp> Ops => new[]");
            w.Open();
            foreach (GraphOpDefinition op in m.Ops.OrderBy(o => o.Code)) w.Line($"GraphOp.{op.Name},");
            w.Line("};", -1);
            w.Indent--;
            w.Line();
            w.Doc("Whether <paramref name=\"op\"/> is an op of the schema.");
            w.Line("public static bool IsDefined(GraphOp op) => (uint)op < (uint)s_signatures.Length && s_signatures[(int)op].Op == op && op != 0;");
            w.Line();
            w.Doc("The schema's signature of <paramref name=\"op\"/>.");
            w.Line("public static GraphOpSignature Signature(GraphOp op)");
            w.Line("    => IsDefined(op) ? s_signatures[(int)op] : throw new ArgumentOutOfRangeException(nameof(op), op, \"not an op of the graph schema\");");
            w.Line();
            w.Doc("Null when an op of <paramref name=\"op\"/> with these counts fits the schema, else why not.");
            w.Line("public static string? Check(GraphOp op, int srcs, int ip, int fp)");
            w.Open();
            w.Line("if (!IsDefined(op)) return $\"op {(int)op} is not an op of the graph schema\";");
            w.Line("GraphOpSignature s = s_signatures[(int)op];");
            w.Line("if (srcs < s.SrcsMin || srcs > s.SrcsMax) return Describe(op, \"operands\", srcs, s.SrcsMin, s.SrcsMax);");
            w.Line("if (ip < s.IpMin || ip > s.IpMax) return Describe(op, \"integer parameters\", ip, s.IpMin, s.IpMax);");
            w.Line("if (fp < s.FpMin || fp > s.FpMax) return Describe(op, \"float parameters\", fp, s.FpMin, s.FpMax);");
            w.Line("return null;");
            w.Close();
            w.Line();
            w.Doc("Throws where <see cref=\"Check\"/> finds the counts do not fit the schema.");
            w.Line("public static void Validate(GraphOp op, int srcs, int ip, int fp)");
            w.Open();
            w.Line("if (Check(op, srcs, ip, fp) is { } error) throw new ArgumentException(error);");
            w.Close();
            w.Line();
            w.Line("private static string Describe(GraphOp op, string what, int count, int min, int max)");
            w.Line("    => $\"{op} takes {(min == max ? min.ToString() : $\"{min}..{max}\")} {what} ({SlotNames(op, what)}); the program gave {count}\";");
            w.Line();
            w.Doc("The slot names of one of an op's lists, as the schema names them (optional ones in brackets).");
            w.Line("public static string SlotNames(GraphOp op, string what) => (op, what[0]) switch");
            w.Open();
            foreach (GraphOpDefinition op in m.Ops)
            {
                foreach ((char tag, GraphSlotList list) in new[] { ('o', op.Srcs), ('i', op.Ip), ('f', op.Fp) })
                {
                    if (list.Slots.Count == 0) continue;
                    string names = string.Join(", ", list.Slots.Select((s, i) => i >= list.Min ? $"[{Camel(s.Name)}]" : Camel(s.Name)));
                    if (list.Variadic) names += ", ...";
                    w.Line($"(GraphOp.{op.Name}, '{tag}') => \"{names}\",");
                }
            }
            w.Line("_ => \"none\",");
            w.Line("};", -1);
            w.Indent--;
            w.Close();
            w.Line();

            // Slot constants.
            w.Doc("The operand and parameter positions of each op (generated from " + SchemaPath + "): an emitter and an executor name a slot instead of interpreting ip[3] or fp[2] on their own. <c>Default*</c> constants are the values the executors fall back on when a program leaves a trailing slot out.");
            w.Line("public static class GraphOpParams");
            w.Open();
            bool firstOp = true;
            foreach (GraphOpDefinition op in m.Ops)
            {
                if (op.Srcs.Slots.Count <= 1 && op.Ip.Slots.Count == 0 && op.Fp.Slots.Count == 0) continue;
                if (!firstOp) w.Line();
                firstOp = false;
                w.Doc($"<see cref=\"GraphOp.{op.Name}\"/>'s slots.");
                w.Line($"public static class {op.Name}");
                w.Open();
                SlotClass(w, "Srcs", op.Srcs, isFloat: false, srcs: true);
                SlotClass(w, "Ip", op.Ip, isFloat: false, srcs: false);
                SlotClass(w, "Fp", op.Fp, isFloat: true, srcs: false);
                w.Close();
            }
            w.Close();
            w.Line();

            // The emitter interface and typed emitters.
            w.Doc("Anything that records graph ops (<see cref=\"GraphProgramBuilder\"/> and the emitters that wrap it): the target of the typed emitters of <see cref=\"GraphOpEmit\"/>.");
            w.Line("public interface IGraphOpEmitter");
            w.Open();
            w.Line("int Op(GraphOp op, ReadOnlySpan<int> srcs, ReadOnlySpan<long> ip = default, ReadOnlySpan<float> fp = default);");
            w.Close();
            w.Line();
            w.Doc("Typed emitters of the schema's ops (generated from " + SchemaPath + "): each takes its operands and parameters by name. An optional operand is left out as -1 (the ones after it must be left out too); an optional parameter left null is left out of the program with every slot after it, so a program keeps the bytes and signature an emitter gave it by hand.");
            w.Line("public static class GraphOpEmit");
            w.Open();
            bool firstEmit = true;
            foreach (GraphOpDefinition op in m.Ops)
            {
                if (op.Srcs.Variadic) continue;   // variadic operands: emitted through Op
                if (!firstEmit) w.Line();
                firstEmit = false;
                Emitter(w, op);
            }
            w.Close();
            w.Close();
            return w.ToString();
        }

        private static void SlotClass(Writer w, string cls, GraphSlotList list, bool isFloat, bool srcs)
        {
            if (list.Slots.Count == 0 || (srcs && list.Slots.Count <= 1 && !list.Variadic)) return;
            w.Line($"public static class {cls}");
            w.Open();
            for (int i = 0; i < list.Slots.Count; i++)
            {
                GraphSlot s = list.Slots[i];
                w.Line($"public const int {Pascal(s.Name)} = {i};");
            }
            if (!srcs)
                foreach (GraphSlot s in list.Slots.Where(s => s.Default != null))
                    w.Line(isFloat
                        ? $"public const float Default{Pascal(s.Name)} = {CsFloat(s.Default!)};"
                        : $"public const long Default{Pascal(s.Name)} = {CsLong(s.Default!)};");
            w.Line($"public const int MinCount = {list.Min}, MaxCount = {list.Max};");
            w.Close();
        }

        private static void Emitter(Writer w, GraphOpDefinition op)
        {
            // Required operands and parameters first (positional), then the optional ones (by name).
            var args = new List<string> { "this IGraphOpEmitter e" };
            foreach (GraphSlot sl in op.Srcs.Slots.Where(x => !x.Optional)) args.Add($"int {Arg(sl.Name)}");
            for (int i = 0; i < op.Ip.Min; i++) args.Add($"long {Arg(op.Ip.Slots[i].Name)}");
            for (int i = 0; i < op.Fp.Min; i++) args.Add($"float {Arg(op.Fp.Slots[i].Name)}");
            foreach (GraphSlot sl in op.Srcs.Slots.Where(x => x.Optional)) args.Add($"int {Arg(sl.Name)} = -1");
            for (int i = op.Ip.Min; i < op.Ip.Slots.Count; i++) args.Add($"long? {Arg(op.Ip.Slots[i].Name)} = null");
            for (int i = op.Fp.Min; i < op.Fp.Slots.Count; i++) args.Add($"float? {Arg(op.Fp.Slots[i].Name)} = null");

            w.Doc($"Records <see cref=\"GraphOp.{op.Name}\"/>.");
            w.Line($"public static int Emit{op.Name}({string.Join(", ", args)})");
            w.Open();
            // Operands.
            int req = op.Srcs.Slots.Count(s => !s.Optional);
            if (op.Srcs.Slots.Count == 0) w.Line("ReadOnlySpan<int> srcs = default;");
            else
            {
                w.Line($"Span<int> srcs = stackalloc int[{op.Srcs.Slots.Count}];");
                for (int i = 0; i < op.Srcs.Slots.Count; i++) w.Line($"srcs[{i}] = {Arg(op.Srcs.Slots[i].Name)};");
                if (req < op.Srcs.Slots.Count)
                {
                    w.Line($"int ns = {req};");
                    for (int i = req; i < op.Srcs.Slots.Count; i++)
                    {
                        string a = Arg(op.Srcs.Slots[i].Name);
                        w.Line($"if ({a} >= 0) {{ if (ns != {i}) throw new ArgumentException(\"{op.Name}: optional operand {a} follows one left out\"); ns = {i + 1}; }}");
                    }
                    w.Line("srcs = srcs[..ns];");
                }
            }
            ParamsBody(w, op.Name, op.Ip, "long", "ip");
            ParamsBody(w, op.Name, op.Fp, "float", "fp");
            w.Line($"return e.Op(GraphOp.{op.Name}, srcs, {(op.Ip.Slots.Count == 0 ? "default" : "ip")}, {(op.Fp.Slots.Count == 0 ? "default" : "fp")});");
            w.Close();
        }

        private static void ParamsBody(Writer w, string opName, GraphSlotList list, string type, string name)
        {
            if (list.Slots.Count == 0) return;
            w.Line($"Span<{type}> {name} = stackalloc {type}[{list.Slots.Count}];");
            for (int i = 0; i < list.Min; i++) w.Line($"{name}[{i}] = {Arg(list.Slots[i].Name)};");
            if (list.Min == list.Slots.Count) return;
            string count = $"n{name}";
            w.Line($"int {count} = {list.Min};");
            for (int i = list.Slots.Count - 1; i >= list.Min; i--)
            {
                string a = Arg(list.Slots[i].Name);
                w.Line($"if ({a}.HasValue && {count} < {i + 1}) {count} = {i + 1};");
            }
            for (int i = list.Min; i < list.Slots.Count; i++)
            {
                GraphSlot sl = list.Slots[i];
                string a = Arg(sl.Name);
                // A slot without a default is meaningful by its presence (a reshape's extents): one left out before a given one
                // is an error, not a default.
                string fill = sl.Default == null
                    ? $"throw new ArgumentException(\"{opName}: {a} is left out before a later parameter\")"
                    : type == "float" ? CsFloat(sl.Default) : CsLong(sl.Default);
                w.Line($"if ({count} > {i}) {name}[{i}] = {a} ?? {fill};");
            }
            w.Line($"{name} = {name}[..{count}];");
        }


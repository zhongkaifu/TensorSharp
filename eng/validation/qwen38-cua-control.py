def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def file_sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as source:
        for chunk in iter(lambda: source.read(8 * 1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def evidence_path(value):
    path = Path(value).resolve()
    if not any(path.is_relative_to(ROOT / p) for p in ("artifacts", "docs/validation")):
        raise argparse.ArgumentTypeError("output must be in ignored artifacts/ or docs/validation/")
    return path


def sources():
    return {"tool": file_sha(HERE), "frozen_bench": file_sha(BENCH), "media_generator": file_sha(GENERATOR)}


def tools(media=False):
    props = {"code": {"type": "string", "pattern": "^[0-9]{4}$"},
             "color": {"type": "string", "enum": [c[0] for c in COLORS]},
             "revision": {"type": "string"}, "step": {"type": "integer", "minimum": 0},
             "lane": {"type": "integer", "minimum": 0}}
    if media:
        props["anchor_code"] = {"type": "string", "pattern": "^[0-9]{4}$"}
    result = [{"type": "function", "function": {"name": "submit_observation",
        "description": "Report the current screenshot and current policy revision; no desktop action is executed.",
        "parameters": {"type": "object", "properties": props, "required": list(props), "additionalProperties": False}}}]
    # A fixed public tool table exercises template rendering without adding a
    # tool-choice advantage for engines supporting a forced-tool grammar.
    for i in range(33):
        result.append({"type": "function", "function": {"name": f"desktop_action_{i:02d}",
            "description": f"Unused desktop action {i}. Do not call for an observation-only task.",
            "parameters": {"type": "object", "properties": {"target": {"type": "string"}},
                           "required": ["target"], "additionalProperties": False}}})
    return result


def expected(seed, lane, step, revision):
    number = 1000 + int(hashlib.sha256(f"{seed}/{lane}/{step}".encode()).hexdigest()[:8], 16) % 9000
    return {"code": str(number), "color": COLORS[(step + lane) % len(COLORS)][0],
            "revision": revision, "step": step, "lane": lane}


def image_png(bench, observation):
    gen = bench.load_generator()
    c = gen.Canvas(1344, 768, (236, 238, 242))
    c.rect(0, 0, 1344, 64, (40, 52, 74))
    c.rect(0, 64, 240, 704, (210, 214, 222))
    c.rect(300, 120, 980, 300, (255, 255, 255))
    c.text(observation["code"], 500, 180, 24, (20, 20, 20))
    rgb = next(rgb for name, rgb in COLORS if name == observation["color"])
    c.rect(480, 490, 500, 180, rgb)
    return c.png()


def user_message(lane, step, url, marker=None, media=False):
    text = (f"Current step={step}, lane={lane}. Inspect this screenshot only for its four-digit code "
            "in the white box and color of the single rectangle below it. Call submit_observation exactly once "
            "with code, color, current revision, step and lane. No other tool or freeform answer. "
            "The current revision is the POLICY_EDIT marker in the first retained user turn; if none, BASE. "
            "The marker overrides every prior assistant/tool report.")
    if media:
        text += (" Also include anchor_code: read the four-digit number in the FIRST retained user screenshot "
                 "(this screenshot itself if no earlier one). Read that image directly; ignore all prior OCR reports.")
    if marker is not None:
        text += f"\nPOLICY_EDIT revision={marker}\n"
    return {"role": "user", "content": [{"type": "text", "text": text},
        {"type": "image_url", "image_url": {"url": url}}]}


def completed_turn(user, result, scope):
    call_id = f"public_{scope}_{result['step']:03d}"
    return [user, {"role": "assistant", "content": "", "tool_calls": [{"id": call_id,
        "type": "function", "function": {"name": "submit_observation", "arguments": canonical(result)}}]},
        {"role": "tool", "tool_call_id": call_id, "content": canonical({"accepted": True, "observation": result})}]


def build_fixture(bench, *, seed=20261101, steps=30, prefix_chars=65536, window=4, tokenizer_path=None, media_probe=False):
    if steps < 1 or prefix_chars < 0 or window < 1:
        raise ValueError("steps/window positive, prefix-chars nonnegative required")
    if media_probe and not 6 <= steps <= 10:
        raise ValueError("opt-in media probe must have 6..10 steps; default 30-step matrix is unchanged")
    table = tools(media_probe)
    padding_unit = "Neutral reference: inspect only the current screenshot; old observations are history, not the current frame.\n"
    padding = (padding_unit * (prefix_chars // len(padding_unit) + 1))[:prefix_chars]
    images, image_cache = {}, {}
    tokenizer = bench.load_tokenizer(tokenizer_path) if tokenizer_path else None
    for lane in (0, 1):
        for step in range(steps):
            data = image_png(bench, expected(seed, lane, step, "BASE"))
            key = f"lane{lane}-step{step:03d}.png"
            images[key] = {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), "width": 1344, "height": 768}
            image_cache[(lane, step)] = (key, data, "data:image/png;base64," + base64.b64encode(data).decode())
    anchor_cache = {}
    if media_probe:
        for lane in (0, 1):
            for step in range(5, steps, 5):
                observation = expected(seed + 100003, lane, step, "BASE")
                # Make the anchor visibly and semantically different even in the
                # unlikely event of the four-digit hash colliding with step0.
                excluded = {expected(seed, lane, s, "BASE")["code"] for s in range(steps)}
                while observation["code"] in excluded:
                    observation["code"] = str(1000 + (int(observation["code"]) - 999) % 9000)
                data = image_png(bench, observation)
                key = f"lane{lane}-anchor-edit{step:03d}.png"
                images[key] = {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), "width": 1344, "height": 768}
                anchor_cache[(lane, step)] = (key, data, "data:image/png;base64," + base64.b64encode(data).decode(), observation["code"])
    rows = []
    scenarios = (MEDIA_SCENARIO,) if media_probe else SCENARIOS
    for scenario in scenarios:
        for lanes in (1, 2):
            for lane in range(lanes):
                scope = f"seed{seed}-{scenario}-c{lanes}-lane{lane}"
                system = {"role": "system", "content": f"Public synthetic CUA observation control. Private case scope: {scope}.\n"
                    "Thinking is disabled. Report only the requested function call. Never perform desktop actions.\n"
                    "The following immutable reference padding contains no screenshot answer.\n" + padding}
                history = []
                anchor_code = expected(seed, lane, 0, "BASE")["code"]
                anchor_key = f"lane{lane}-step000.png"
                previous_messages = None
                for step in range(steps):
                    dropped = []
                    if scenario == "truncate" and len(history) > window:
                        dropped = [step - len(history) + j for j in range(len(history) - window)]
                        history = history[-window:]
                    revision = f"R{step // 5:03d}" if scenario == "edit" else "BASE"
                    edited = scenario == "edit" and step > 0 and step % 5 == 0
                    if scenario == "edit" and history:
                        first = history[0][0]["content"][0]["text"]
                        before, mark = first.rsplit("POLICY_EDIT revision=", 1)
                        history[0][0]["content"][0]["text"] = before + "POLICY_EDIT revision=" + revision + "\n"
                    edited_media = None
                    if scenario == MEDIA_SCENARIO and history and step % 5 == 0:
                        key, data, url, anchor_code = anchor_cache[(lane, step)]
                        edited_media = {"message_index": 1, "image_content_part": 1, "old_image": anchor_key,
                            "old_sha256": images[anchor_key]["sha256"], "new_image": key,
                            "new_sha256": images[key]["sha256"], "early_user_text_changed": False}
                        history[0][0]["content"][1]["image_url"]["url"] = url
                        anchor_key = key
                    key, data, url = image_cache[(lane, step)]
                    current = user_message(lane, step, url, revision if scenario == "edit" and step == 0 else None,
                        media=scenario == MEDIA_SCENARIO)
                    messages = [system] + [message for turn in history for message in turn] + [current]
                    # Deep-copy before subsequent policy edits mutate a retained turn.
                    messages = json.loads(json.dumps(messages))
                    observation = expected(seed, lane, step, revision)
                    if scenario == MEDIA_SCENARIO:
                        observation["anchor_code"] = anchor_code
                    common = {"messages": messages, "tools": table, "tool_choice": "auto", "max_tokens": 192,
                        "temperature": 0, "top_p": 1, "presence_penalty": 0, "frequency_penalty": 0,
                        "seed": 1234, "stream": True, "stream_options": {"include_usage": True}}
                    shared = 0
                    if previous_messages:
                        for a, b in zip(previous_messages, messages):
                            if a != b: break
                            shared += 1
                    rows.append({"scenario": scenario, "lanes": lanes, "lane": lane, "step": step,
                        "scope": scope, "common": common, "common_sha256": digest(common), "expected": observation,
                        "history": {"retained_complete_turns": len(history), "dropped_steps": dropped,
                            "policy_edit_this_step": edited, "edit_target": "first retained user POLICY_EDIT" if edited else None,
                            "old_media_edit_this_step": edited_media is not None, "edited_media": edited_media,
                            "equal_leading_messages_vs_prior_request": shared, "token_prefix_reuse_is_NOT_inferred": True},
                        "current_image": key, "immutable_system_sha256": digest(system)})
                    if tokenizer:
                        texts = [canonical(table)]
                        for message in messages:
                            content = message.get("content")
                            if isinstance(content, str): texts.append(content)
                            elif isinstance(content, list): texts.extend(p["text"] for p in content if p.get("type") == "text")
                            if message.get("tool_calls"): texts.append(canonical(message["tool_calls"]))
                        rows[-1]["text_only_tokenizer_estimate"] = sum(len(tokenizer.encode(t, add_special_tokens=False).ids) for t in texts)
                    history.append(completed_turn(current, observation, scope))
                    previous_messages = messages
    fixture = {"schema": VERSION + "/fixture", "seed": seed, "steps": steps, "window": window,
        "prefix_chars": prefix_chars, "max_tokens": 192, "concurrency_cases": [1, 2], "scenarios": list(scenarios),
        "protocol": "opt_in_6_to_10_step_old_media_probe" if media_probe else "default_three_scenarios",
        "standard_30step_protocol": steps == 30 and not media_probe, "declared_context_capacity": 65536,
        "sources": sources(), "tools_sha256": digest(table),
        "text_tokenizer_estimate": {"status": "RECORDED_TEXT_ONLY" if tokenizer else "NOT_RUN", "sha256": file_sha(tokenizer_path) if tokenizer_path else None,
            "definition": "sum of text/tool JSON encodings excluding template wrapper/special tokens and ALL image expansion; NOT actual prompt usage"},
        "zlib_version": zlib.ZLIB_VERSION, "images": images, "limitations": LIMITS, "requests": rows}
    image_data = {key: data for (key, data, url) in image_cache.values()}
    image_data.update({key: data for (key, data, url, code) in anchor_cache.values()})
    return fixture, image_data


def prepare(args):
    args.out.mkdir(parents=True, exist_ok=False)
    steps = args.steps if args.steps is not None else (10 if args.media_probe else 30)
    fixture, images = build_fixture(load_bench(), seed=args.seed, steps=steps,
        prefix_chars=args.prefix_chars, window=args.window, tokenizer_path=args.tokenizer, media_probe=args.media_probe)
    (args.out / "images").mkdir()
    for key, data in images.items():
        (args.out / "images" / key).write_bytes(data)
    path = args.out / "fixture.json"
    path.write_text(canonical(fixture) + "\n")
    manifest = {"schema": VERSION + "/prepared", "fixture_sha256": file_sha(path), "requests": len(fixture["requests"]),
        "sources": fixture["sources"], "images": fixture["images"], "standard_30step_protocol": fixture["standard_30step_protocol"],
        "protocol": fixture["protocol"],
        "declared_context_capacity": fixture["declared_context_capacity"], "text_tokenizer_estimate": fixture["text_tokenizer_estimate"],
        "status": "PREPARED_NOT_RUN", "network": "NOT_RUN", "GPU": "NOT_RUN"}
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({k: v for k, v in manifest.items() if k not in ("images", "sources")}, indent=2))
    return 0


def load_fixture(directory):
    manifest = json.loads((directory / "manifest.json").read_text())
    path = directory / "fixture.json"
    if manifest["fixture_sha256"] != file_sha(path):
        raise ValueError("fixture hash changed")
    fixture = json.loads(path.read_text())
    if fixture.get("schema") != VERSION + "/fixture" or fixture["sources"] != sources() or manifest["sources"] != sources():
        raise ValueError("fixture protocol/client/generator changed; prepare a new common fixture")
    media_probe = fixture.get("protocol") == "opt_in_6_to_10_step_old_media_probe"
    prepared_scenarios = (MEDIA_SCENARIO,) if media_probe else SCENARIOS
    if fixture["scenarios"] != list(prepared_scenarios) or fixture["max_tokens"] != 192 or fixture["tools_sha256"] != digest(tools(media_probe)):
        raise ValueError("fixed tool/output contract changed")
    for name, meta in fixture["images"].items():
        if Path(name).name != name or file_sha(directory / "images" / name) != meta["sha256"]:
            raise ValueError("prepared image changed")
    identities = set()
    for row in fixture["requests"]:
        identity = tuple(row[k] for k in ("scenario", "lanes", "lane", "step"))
        if identity in identities or row["common_sha256"] != digest(row["common"]):
            raise ValueError("duplicate/changed request")
        identities.add(identity)
        if row["immutable_system_sha256"] != digest(row["common"]["messages"][0]):
            raise ValueError("immutable prefix identity changed")
    required = {(s, n, lane, step) for s in prepared_scenarios for n in (1, 2) for lane in range(n) for step in range(fixture["steps"])}
    if identities != required:
        raise ValueError("incomplete fixture plan")
    return fixture, manifest


def captured_stream(bench, url, body, timeout, opener=None):
    """Run the frozen stream function code with a request-local transport tap.

    No global monkeypatch: each concurrent request has its own globals copy and
    urllib namespace. Raw bytes, including HTTP error bodies, are retained.
    """
    wire = {"chunks": [], "status": None, "headers": [], "done": False, "closed_normally": False,
        "capture_scope": "exact_bytes_consumed_by_frozen_client_through_DONE_or_EOF; unread_HTTP_tail_not_claimed"}
    opener = opener or urllib.request.urlopen

    class Tap:
        def __init__(self, response): self.response = response
        @property
        def status(self): return self.response.status
        def __enter__(self):
            self.response.__enter__()
            return self
        def __exit__(self, *args):
            result = self.response.__exit__(*args)
            if args[0] is None: wire["closed_normally"] = True
            return result
        def __iter__(self):
            for raw in self.response:
                wire["chunks"].append(raw)
                line = raw.strip()
                if line.startswith(b"data:") and line[5:].strip() == b"[DONE]": wire["done"] = True
                yield raw

    def opened(request, **kwargs):
        wire["request_body_sha256"] = hashlib.sha256(request.data or b"").hexdigest()
        wire["request_body_bytes"] = len(request.data or b"")
        try:
            response = opener(request, **kwargs)
        except urllib.error.HTTPError as error:
            payload = error.read()
            wire.update(status=error.code, headers=list(error.headers.items()) if error.headers else [])
            wire["chunks"].append(payload)
            error.close()
            raise urllib.error.HTTPError(error.url, error.code, error.msg, error.headers, io.BytesIO(payload)) from error
        wire.update(status=response.status, headers=list(response.headers.items()) if response.headers else [])
        return Tap(response)

    namespace = bench.stream_chat.__globals__.copy()
    namespace["urllib"] = types.SimpleNamespace(error=urllib.error,
        request=types.SimpleNamespace(Request=urllib.request.Request, urlopen=opened))
    stream = types.FunctionType(bench.stream_chat.__code__, namespace, bench.stream_chat.__name__)
    obs = stream(url, body, timeout)
    data = b"".join(wire.pop("chunks"))
    wire.update(body_base64=base64.b64encode(data).decode(), body_sha256=hashlib.sha256(data).hexdigest(), bytes=len(data))
    return obs, wire


def positive_int(value):
    return isinstance(value, int) and not isinstance(value, bool) and value > 0


def validate(bench, result, wire, observation, max_tokens, schema=None):
    calls = result.get("tool_calls") or []
    parsed = calls[0].get("parsed") if len(calls) == 1 else None
    schema_errors = bench.validate_schema(parsed, schema or tools()[0]["function"]["parameters"])
    checks = {"http_success": result.get("http_status") == 200 and not result.get("error"),
        "single_choice": not result.get("multiple_choices"),
        "stream_complete": wire.get("done") is True and wire.get("closed_normally") is True
            and result.get("finish_reason") in ("stop", "tool_calls", "function_call"),
        "no_hidden_thinking": not result.get("reasoning") and not result.get("reasoning_chars")
            and not any(marker in result.get("content", "") for marker in ("<think>", "</think>")),
        "one_correct_tool": len(calls) == 1 and calls[0].get("name") == "submit_observation",
        "typed_exact_arguments": not schema_errors and parsed == observation,
        "no_freeform_answer": not (result.get("content") or "").strip()}
    usage = result.get("raw_usage")
    valid_usage = isinstance(usage, dict) and positive_int(usage.get("prompt_tokens")) \
        and positive_int(usage.get("completion_tokens")) and usage["completion_tokens"] <= max_tokens
    finite_times = all(isinstance(result.get(key), (int, float)) and not isinstance(result[key], bool)
                       and math.isfinite(result[key]) and result[key] > 0 for key in ("ttft_s", "total_s"))
    measurement = {"actual_server_usage": bool(valid_usage), "finite_client_timings": finite_times,
                   "ttft_within_request": finite_times and result["ttft_s"] <= result["total_s"]}
    return {"verdict": "PASS" if all(checks.values()) else "FAIL", "checks": checks,
        "schema_errors": schema_errors, "measurement_verdict": "PASS" if all(measurement.values()) else "UNVERIFIED",
        "measurement_checks": measurement, "latency_qualified": all(checks.values()) and all(measurement.values())}


def measure(bench, client, row, timeout, opener=None):
    common = row["common"]
    extra = {k: v for k, v in common.items() if k not in ("messages", "max_tokens")}
    body = client.body(common["messages"], common["max_tokens"], extra)
    obs, wire = captured_stream(bench, client.url, body, timeout, opener)
    try:
        result = client.finish(obs)
    except Exception as error:
        result = {"error": f"frozen_client_normalization: {type(error).__name__}: {error}",
            "http_status": obs.get("http_status"), "finish_reason": obs.get("finish_reason"),
            "content": "".join(obs.get("content") or []), "reasoning": "".join(obs.get("reasoning") or []),
            "reasoning_chars": sum(len(c) for c in obs.get("reasoning") or []), "tool_calls": [],
            "ttft_s": None, "total_s": obs["t_end"] - obs["t0"]}
    result["raw_usage"] = obs["usage"]
    result["multiple_choices"] = obs.get("multiple_choices", False)
    quality = validate(bench, result, wire, row["expected"], common["max_tokens"], common["tools"][0]["function"]["parameters"])
    # Tools are parser output. Never expose the client's legacy diagnostic rate
    # as a valid CUA decode speed, even if a noncompliant server emits prose.
    result["decode_tok_s"] = None
    result["decode_unavailable_reason"] = "CUA_tool_parser_stream_not_raw_target_token_stream"
    result.pop("legacy_completion_minus_one_decode_tok_s", None)
    return {"kind": "request", "scenario": row["scenario"], "lanes": row["lanes"], "lane": row["lane"],
        "step": row["step"], "scope": row["scope"], "history": row["history"], "expected": row["expected"],
        "common_sha256": row["common_sha256"], "full_body_sha256": digest(body),
        "wire_request_body_sha256": wire.get("request_body_sha256"),
        "canonical_input_sha256": digest({k: v for k, v in body.items() if k != "model"}),
        "frozen_normalized_request_sha256": digest(bench.request_identity(body)),
        "request_body": body, "raw_observation": obs, "raw_transport": wire, "response": result,
        "quality": quality, "output": {"content_utf8_bytes": len(result["content"].encode()),
            "reasoning_utf8_bytes": len(result["reasoning"].encode()), "tool_calls": len(result["tool_calls"]),
            "tool_arguments_utf8_bytes": sum(len(c["arguments"].encode()) for c in result["tool_calls"]),
            "completion_tokens": obs["usage"].get("completion_tokens") if isinstance(obs["usage"], dict) else None,
            "token_source": "actual_server_usage_only"}}


def summarise(rows, waves, expected_count):
    complete = len(rows) == expected_count and len({(r["lane"], r["step"]) for r in rows}) == expected_count
    qualified = complete and bool(rows) and all(r["quality"]["latency_qualified"] for r in rows)
    metric = lambda key: statistics.median(r["response"][key] for r in rows) if qualified else None
    return {"complete_request_count": complete, "expected_requests": expected_count, "observed_requests": len(rows),
        "quality_pass": sum(r["quality"]["verdict"] == "PASS" for r in rows), "quality_total": expected_count,
        "measurement_pass": sum(r["quality"]["measurement_verdict"] == "PASS" for r in rows),
        "latency_qualified": qualified, "qualified_ttft_median_s": metric("ttft_s"), "qualified_e2e_median_s": metric("total_s"),
        "qualified_wave_wall_total_s": sum(w["wall_s"] for w in waves) if qualified else None,
        "qualified_server_completion_tokens": sum(r["output"]["completion_tokens"] for r in rows) if qualified else None,
        "failure_note": None if qualified else "Latency aggregate withheld: failed/incomplete quality or unavailable actual usage/timing; raw observations retained.",
        "CI": "NONE; 30 correlated sequential waves, not 30 independent runs", "decode_tok_s": None}


def execute_case(bench, client, selected, steps, lanes, timeout, write, measure_fn=measure):
    by_key = {(r["lane"], r["step"]): r for r in selected}
    if set(by_key) != {(lane, step) for lane in range(lanes) for step in range(steps)} or len(selected) != len(by_key):
        raise ValueError("missing or duplicate planned lane/step")
    rows, waves = [], []
    with ThreadPoolExecutor(max_workers=lanes) as pool:
        for step in range(steps):
            barrier = threading.Barrier(lanes)
            def one(lane):
                barrier.wait(timeout=30)
                return measure_fn(bench, client, by_key[(lane, step)], timeout)
            start = time.perf_counter()
            futures = [pool.submit(one, lane) for lane in range(lanes)]
            current = [f.result() for f in futures]
            wave = {"kind": "wave", "scenario": selected[0]["scenario"], "lanes": lanes, "step": step,
                "wall_s": time.perf_counter() - start, "arrival_policy": "barrier_each_step_no_client_think_time"}
            for row in current:
                rows.append(row); write(row)
            waves.append(wave); write(wave)
    return summarise(rows, waves, steps * lanes)


def validate_deployment(launch, args, fixture):
    if not isinstance(launch, dict) or not launch or launch.get("engine") != args.engine:
        raise ValueError("launch manifest must identify this actual engine")
    if (args.context_capacity != fixture["declared_context_capacity"]
            or launch.get("context_tokens") != args.context_capacity
            or not positive_int(launch.get("lanes")) or launch["lanes"] < args.lanes):
        raise ValueError("manifest must record the common CTX65536 and sufficient server lanes; no automatic truncation")
    if args.engine == "tensorsharp":
        environment = launch.get("environment") or {}
        if "TS_PREFIX_CACHE_ISOLATION" not in environment:
            raise ValueError("TS manifest must explicitly record TS_PREFIX_CACHE_ISOLATION, including null when unset")
        actual = (environment["TS_PREFIX_CACHE_ISOLATION"] or "lineage").strip().lower()
        required = {"default-lineage": "lineage", "trusted-single-tenant-shared": "shared"}.get(args.cache_profile)
        if required is None or actual != required:
            raise ValueError("TS cache-profile declaration differs from manifest; client never changes isolation")
    elif args.cache_profile != "engine-native-global":
        raise ValueError("external engines require explicit engine-native-global declaration; match trusted-shared TS group")


def run(args):
    fixture, fixture_manifest = load_fixture(args.fixtures)
    launch = json.loads(args.manifest.read_text())
    validate_deployment(launch, args, fixture)
    bench = load_bench()
    client_args = types.SimpleNamespace(engine=args.engine, url=args.url, model=args.model, extra_body=None,
        metrics_url="", tokenizer=None, server_log=None, timeout=args.timeout, temperature=0, top_p=1, sampling_seed=1234)
    client = bench.Client(client_args) # model is required: never discover/warm up implicitly
    scenarios = args.scenarios.split(",") if args.scenarios else fixture["scenarios"]
    if len(set(scenarios)) != len(scenarios) or not set(scenarios) <= set(fixture["scenarios"]):
        raise ValueError("invalid/duplicate scenario selection")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    summaries = []
    with args.out.open("x") as output:
        def write(row): output.write(canonical(row) + "\n"); output.flush()
        write({"kind": "run", "schema": VERSION, "created_utc": datetime.now(timezone.utc).isoformat(),
            "engine": args.engine, "mode": args.mode, "label": args.label, "url": args.url, "model": args.model,
            "lanes": args.lanes, "steps": fixture["steps"], "selected_scenarios": scenarios,
            "context_capacity_operator_declaration": args.context_capacity,
            "cache_profile_operator_declaration": args.cache_profile,
            "cache_comparison_group": "trusted-single-tenant-prefix" if args.cache_profile in ("trusted-single-tenant-shared", "engine-native-global") else "default-lineage-diagnostic",
            "cache_profile_limit": "operator declaration must agree with actual launch manifest; this tool does not configure or prove engine cache isolation",
            "standard_30step_protocol": fixture["standard_30step_protocol"], "sources": sources(),
            "protocol": fixture["protocol"],
            "fixture_path": str(args.fixtures), "fixture_manifest": fixture_manifest,
            "launch_manifest": launch, "launch_manifest_sha256": file_sha(args.manifest),
            "settings": {"temperature": 0, "top_p": 1, "seed": 1234, "thinking": False,
                "tool_choice": "auto", "max_tokens": 192, "warmup": "NONE", "prior_history": "prescribed"},
            "identity_definitions": {"common_sha256": "canonical JSON of prepared portable fields, before frozen engine adapters",
                "full_body_sha256": "canonical JSON of entire actual body, including model and every adapter field",
                "canonical_input_sha256": "canonical JSON of actual body removing ONLY model routing ID; tool IDs and adapters retained",
                "wire_request_body_sha256": "SHA256 of exact bytes supplied to the HTTP request by frozen stream_chat",
                "frozen_normalized_request_sha256": "frozen helper removes model and normalizes historical tool IDs; diagnostic only, not byte identity"},
            "engine_body_adapter_example": {k: v for k, v in client.body([], 192).items() if k not in ("model", "messages")},
            "timeout_s": args.timeout, "limitations": LIMITS, "hardware_counters": "NOT_RUN"})
        for scenario in scenarios:
            selected = [r for r in fixture["requests"] if r["scenario"] == scenario and r["lanes"] == args.lanes]
            summary = execute_case(bench, client, selected, fixture["steps"], args.lanes, args.timeout, write)
            summary.update(kind="case_summary", scenario=scenario, lanes=args.lanes)
            summaries.append(summary); write(summary)
        passed = bool(summaries) and all(s["latency_qualified"] for s in summaries)
        write({"kind": "run_end", "complete": True, "qualified": passed,
            "status": "ALL_SELECTED_CASES_QUALIFIED" if passed else "QUALITY_OR_MEASUREMENT_FAILED",
            "summaries": summaries, "original_benchmark_scores_changed": False})
    print(json.dumps({"out": str(args.out), "qualified": passed, "summaries": summaries}, indent=2))
    return 0 if passed else 1



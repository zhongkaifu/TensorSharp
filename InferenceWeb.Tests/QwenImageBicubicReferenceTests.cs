using System.Security.Cryptography;
using System.Text.Json;

namespace InferenceWeb.Tests;

// Pixel goldens are generated independently by Pillow12.3.0, without importing
// or reimplementing TensorSharp's resampler. These are CPU preprocessing tests;
// they do not qualify a vision encoder, a GPU, or generated-answer quality.
public sealed class QwenImageBicubicReferenceTests
{
    private static readonly ReferenceDocument Reference = LoadReference();

    public static IEnumerable<object[]> ReferenceCases()
        => Reference.Cases.Select(row => new object[] { row.Name });

    public static IEnumerable<object[]> AutomaticResizeCases()
        => Reference.Cases.Where(row => row.AutomaticResize).Select(row => new object[] { row.Name });

    [Theory]
    [MemberData(nameof(ReferenceCases))]
    public void ByteBicubicMatchesIndependentPillowPixels(string name)
    {
        ReferenceCase row = Find(name);
        byte[] rgba = Convert.FromBase64String(row.InputRgbaBase64);
        Assert.Equal(checked(4 * row.SourceWidth * row.SourceHeight), rgba.Length);
        Assert.Equal(row.InputRgbaSha256, Hash(rgba));
        float[] actual = ImageProcessorUtils.ResizeRgbaToChannelFirstBicubicByte(
            rgba, row.SourceWidth, row.SourceHeight, row.TargetWidth, row.TargetHeight);
        AssertPixels(row, actual);
    }

    [Theory]
    [MemberData(nameof(ReferenceCases))]
    public void ExplicitSizePublicProcessorMatchesIndependentPillowPixels(string name)
    {
        ReferenceCase row = Find(name);
        string path = WriteFixturePng(row);
        try
        {
            var processor = new Qwen35ImageProcessor(patchSize: 1, mergeSize: 1,
                shortestEdge: 1, longestEdge: 4096);
            float[] actual = processor.ProcessImage(path, row.TargetHeight, row.TargetWidth);
            AssertPixels(row, actual);
        }
        finally { File.Delete(path); }
    }

    [Theory]
    [MemberData(nameof(AutomaticResizeCases))]
    public void AutomaticSizePublicProcessorMatchesIndependentPillowPixels(string name)
    {
        ReferenceCase row = Find(name);
        string path = WriteFixturePng(row);
        try
        {
            var processor = new Qwen35ImageProcessor(patchSize: 1, mergeSize: 1,
                shortestEdge: row.MinimumPixels, longestEdge: row.MaximumPixels);
            var (pixels, height, width) = processor.ProcessImage(path);
            Assert.Equal(row.TargetWidth, width);
            Assert.Equal(row.TargetHeight, height);
            AssertPixels(row, pixels);
        }
        finally { File.Delete(path); }
    }

    private static void AssertPixels(ReferenceCase row, float[] actual)
    {
        byte[] expected = Convert.FromBase64String(row.ExpectedRgbBase64);
        int pixels = checked(row.TargetWidth * row.TargetHeight);
        Assert.Equal(checked(3 * pixels), expected.Length);
        Assert.Equal(expected.Length, actual.Length);
        Assert.Equal(row.ExpectedRgbSha256, Hash(expected));
        for (int pixel = 0; pixel < pixels; ++pixel)
        {
            for (int channel = 0; channel < 3; ++channel)
            {
                byte referenceByte = expected[3 * pixel + channel];
                float value = actual[channel * pixels + pixel];
                Assert.True(float.IsFinite(value), $"{row.Name}: nonfinite pixel{pixel}/channel{channel}");
                Assert.InRange(value, -1f, 1f);
                // Independently generated byte is the oracle. This tolerance is
                // only normalization rounding (<1/30000 of a byte), not an image
                // comparison tolerance that could conceal a wrong resampler.
                double referenceNormalized = referenceByte / 127.5 - 1.0;
                Assert.True(Math.Abs(value - referenceNormalized) <= 0.00000024,
                    $"{row.Name}: pixel{pixel}/channel{channel}, expected byte{referenceByte}, actual normalized{value:R}");
                Assert.Equal((int)referenceByte, (int)MathF.Round((value + 1f) * 127.5f));
            }
        }
    }

    private static string WriteFixturePng(ReferenceCase row)
    {
        string path = Path.Combine(Path.GetTempPath(), $"tensorsharp-qwen-bicubic-{Guid.NewGuid():N}.png");
        File.WriteAllBytes(path, Convert.FromBase64String(row.InputPngBase64));
        return path;
    }

    private static ReferenceCase Find(string name) => Reference.Cases.Single(row => row.Name == name);
    private static string Hash(byte[] bytes) => Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();

    private static ReferenceDocument LoadReference()
    {
        using Stream stream = typeof(QwenImageBicubicReferenceTests).Assembly.GetManifestResourceStream(
            "InferenceWeb.Tests.Fixtures.QwenImageBicubic.reference.json")
            ?? throw new InvalidDataException("Missing independent Pillow pixel fixture.");
        var document = JsonSerializer.Deserialize<ReferenceDocument>(stream)
            ?? throw new InvalidDataException("Invalid independent Pillow pixel fixture.");
        if (document.Schema != "qwen-byte-bicubic-pillow-reference.v1" || document.PillowVersion != "12.3.0"
            || document.Cases.Length != 11 || document.Cases.Select(row => row.Name).Distinct().Count() != 11)
            throw new InvalidDataException("Unexpected independent pixel oracle identity/coverage.");
        return document;
    }

    private sealed record ReferenceDocument(string Schema, string PillowVersion, ReferenceCase[] Cases);
    private sealed record ReferenceCase(string Name, int SourceWidth, int SourceHeight,
        int TargetWidth, int TargetHeight, string InputRgbaBase64, string InputPngBase64,
        string ExpectedRgbBase64, string InputRgbaSha256, string ExpectedRgbSha256,
        bool AutomaticResize, int MinimumPixels = 0, int MaximumPixels = 0);
}

    private static string LowBitDq8(int i) => i switch
    {
        0 => "tensorsharp_dq8_lowbit_q2k", 1 => "tensorsharp_dq8_lowbit_q3k", 2 => "tensorsharp_dq8_iq2_xs",
        3 => "tensorsharp_dq8_iq1_s", _ => "tensorsharp_dq8_iq1_m",
    };

    /// <summary>y [rows, outDim] = input [rows, inDim] W^T for a raw Q2_K, Q3_K, IQ2_XS, IQ1_S or IQ1_M weight:
    /// the simdgroup_matrix kernel from <see cref="Iq2XxsMatmulSimdgroupMinRows"/> rows, else one threadgroup per output.</summary>
    internal static MlxArray LowBitMatmul(int ggmlType, MlxArray input, MlxArray rawWeight, int rows, int inDim, int outDim)
    {
        int i = LowBitIndex(ggmlType);
        if (i < 0) throw new NotSupportedException($"No low-bit device kernel for GGML type {(GgmlTensorType)ggmlType}.");
        MlxArray gemm = TryPerElementDequantMatmul(input, rawWeight, rows, inDim, outDim, LowBitLabel(i), LowBitTypes[i].Dequant,
            LowBitTypes[i].BlockBytes, LowBitQuantHeader);
        if (gemm.IsValid)
            return gemm;
        MlxArray fewRow = TryFewRowMatmul(input, rawWeight, rows, inDim, outDim, LowBitLabel(i), LowBitDq8(i), LowBitTypes[i].BlockBytes,
            LowBitQuantHeader + Dq8LowBit);
        if (fewRow.IsValid)
            return fewRow;
        if (rows >= Iq2XxsMatmulSimdgroupMinRows)
        {
            try { return IQuantMatmulSimdgroup(input, rawWeight, rows, inDim, outDim, () => EnsureLowBitMatmulSgKernel(i), LowBitLabel(i)); }
            catch (NotSupportedException) { }
        }
        return IQuantMatmul(input, rawWeight, rows, inDim, outDim, () => EnsureLowBitMatmulKernel(i), LowBitLabel(i));
    }

    internal static MlxArray LowBitGetRows(int ggmlType, MlxArray rawWeight, MlxArray indices, int rows, int inDim)
    {
        int i = LowBitIndex(ggmlType);
        if (i < 0) throw new NotSupportedException($"No low-bit device kernel for GGML type {(GgmlTensorType)ggmlType}.");
        return IQuantGetRows(rawWeight, indices, rows, inDim, () => EnsureLowBitGetRowsKernel(i), LowBitLabel(i));
    }

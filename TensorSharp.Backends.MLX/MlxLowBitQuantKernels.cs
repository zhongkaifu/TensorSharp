    const float g = float(uint((kIq2XsGrid[q & 511] >> (8 * j)) & 255ul));
    const uint signs = tensorsharp_iq2_signs(uint(q >> 9));
    return db * g * (((signs >> j) & 1u) != 0u ? -1.0f : 1.0f);
}

// block_iq1_s: d (half) | qs[32] | qh[8] (ushort) = 50 bytes; grid values in {-1, 0, 1} plus +/-1/8.
inline float tensorsharp_dequant_iq1_s(const device uchar * block, int e) {
    const float d = float(*reinterpret_cast<const device half *>(block));
    const int ib = e >> 5, l = (e >> 3) & 3, j = e & 7;
    const ushort qh = *reinterpret_cast<const device ushort *>(block + 34 + 2 * ib);
    const float dl = d * float(2 * ((qh >> 12) & 7) + 1);
    const float delta = (qh & 0x8000) != 0 ? -0.125f : 0.125f;
    const uint index = uint(block[2 + 4 * ib + l]) | (uint((qh >> (3 * l)) & 7) << 8);
    const float g = float(char((kIq1SGrid[index] >> (8 * j)) & 255ul));
    return dl * (g + delta);
}

// block_iq1_m: qs[32] | qh[16] | scales[4] (ushort; the half super-block scale in their top nibbles) = 56 bytes.
inline float tensorsharp_dequant_iq1_m(const device uchar * block, int e) {
    const device ushort * sc = reinterpret_cast<const device ushort *>(block + 48);
    const ushort scaleBits = ushort((sc[0] >> 12) | ((sc[1] >> 8) & 0x00f0) | ((sc[2] >> 4) & 0x0f00) | (sc[3] & 0xf000));
    const float d = float(as_type<half>(scaleBits));
    const int ib = e >> 5, l = (e >> 3) & 3, j = e & 7;
    const ushort s = sc[ib >> 1];
    const int shift = 6 * (ib & 1) + ((l >> 1) != 0 ? 3 : 0);
    const float dl = d * float(2 * ((s >> shift) & 7) + 1);
    const uint qhb = uint(block[32 + 2 * ib + (l >> 1)]);
    const uint index = uint(block[4 * ib + l]) | ((qhb << (8 - 4 * (l & 1))) & 0x700u);
    const float delta = (qhb & (0x08u << (4 * (l & 1)))) != 0u ? -0.125f : 0.125f;
    const float g = float(char((kIq1SGrid[index] >> (8 * j)) & 255ul));
    return dl * (g + delta);
}


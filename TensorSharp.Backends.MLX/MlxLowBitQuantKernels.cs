    internal static bool IsLowBitDeviceType(int ggmlType) => LowBitIndex(ggmlType) >= 0;

    private static int LowBitIndex(int ggmlType)
    {
        for (int i = 0; i < LowBitTypes.Length; i++)
            if ((int)LowBitTypes[i].Type == ggmlType)
                return i;
        return -1;
    }

    internal static int LowBitBlockBytes(int ggmlType)
    {
        int i = LowBitIndex(ggmlType);
        if (i < 0) throw new NotSupportedException($"No low-bit device kernel for GGML type {(GgmlTensorType)ggmlType}.");
        return LowBitTypes[i].BlockBytes;
    }

